def find_containing_func(addr, funcs):
    """Return the function whose address range contains addr, or None.
    Uses func_lo so absorbed orphan prefixes count as part of the body."""
    for f in funcs:
        if func_lo(f) <= addr <= f['end']:
            return f
    return None

def emit_track_hooks(rows, funcs_by_start, symbols, external_entries, wrapper_names):
    """src/gen/revs_track_hooks.[ch] — one region-form C function per circuit, plus the
    address→body dispatch src/platform/track.c consults.

    ⚠ The dispatch is BY CIRCUIT INDEX AND ADDRESS, and both halves matter: $5572 exists in every
    circuit and is different code in each.  A dispatch on address alone would compile, run, and
    drive Brands Hatch's corner through Snetterton's hook."""
    # ⭐ revs_track_hook() ITSELF is emitted here, not in src/platform/track.c, and the file is
    # always written even with zero circuits.  Two reasons, both structural:
    #   * it calls the bodies, so putting it in track.c would make every consumer of track.c link
    #     the whole transliteration — including tools/validate_tracks.c, whose value is being a
    #     small differential that runs no engine code;
    #   * the engine's generated C references it unconditionally, so a build with no hook bodies
    #     still needs the symbol.  Emitting a trapping version is the honest form of "absent".
    seam = [
        '/* The engine→track-file seam.  src/platform/platform_c.h declares it; the per-circuit',
        ' * extents in revs_gen.c call it with a $5300-$5A25 target.  ⚠ g_track, not',
        ' * g_trackInstalled: this is the circuit the engine is RUNNING, and the patched operands',
        ' * in mem[] belong to it. */',
        'unsigned long g_trackHookMissing = 0;',
        'uint16_t      g_trackHookMissingAddr = 0;',
        '/* ⭐ SUCCESSFUL calls, and this one is not decoration.  "the circuit installed and did',
        ' * not crash" is compatible with the hooks never being reached at all — which is exactly',
        ' * what an expansion circuit running Silverstone\'s control flow would look like.  A',
        ' * non-zero count here is the evidence that the per-circuit code actually EXECUTES. */',
        'unsigned long g_trackHookCalls = 0;',
        '',
        'void revs_track_hook(uint16_t addr)',
        '{',
        '    if (revs_track_hook_call(g_track, (unsigned short)addr)) { g_trackHookCalls++; return; }',
        '    /* No body for this circuit at this address: record the FIRST, count them all.',
        '       ⚠ Never fall back to the unpatched engine routine — the patch replaced it',
        '       precisely because this circuit needs different behaviour there. */',
        '    if (g_trackHookMissing == 0) g_trackHookMissingAddr = addr;',
        '    g_trackHookMissing++;',
        '    platform_smc_unhandled(0x5A22, addr);',
        '}',
        '',
    ]

    if not rows:
        OUT_HOOKS_H.write_text(
            '/* GENERATED by tools/transpile.py — DO NOT EDIT.  No circuit has hook bodies in\n'
            ' * this build (REVS_TRACK_HOOKS=0, or no expansion disc present), so every expansion\n'
            ' * circuit is refused by revs_track_check() and the seam always traps. */\n'
            '#ifndef REVS_TRACK_HOOKS_H\n#define REVS_TRACK_HOOKS_H\n'
            '#define REVS_TRACK_HOOK_CIRCUITS 0\n'
            '/* `inline` so a consumer that needs only one of the two (track.c needs _has, the\n'
            ' * generated bodies need _call) does not draw an unused-function warning. */\n'
            '#define REVS_HOOK_FN inline\n'
            'static REVS_HOOK_FN int revs_track_hook_has(unsigned char t, unsigned short a)\n'
            '{ (void)t; (void)a; return 0; }\n'
            'static REVS_HOOK_FN int revs_track_hook_call(unsigned char t, unsigned short a)\n'
            '{ (void)t; (void)a; return 0; }\n'
            '#endif\n')
        OUT_HOOKS.write_text('\n'.join(
            ['/* GENERATED by tools/transpile.py — DO NOT EDIT.  No hook bodies in this build. */',
             '#include "../cpu/cpu.h"',
             '#include "../platform/platform_c.h"',
             '#include "../platform/track.h"',
             '#include "revs_track_hooks.h"',
             ''] + seam) + '\n')
        print(f'Wrote {OUT_HOOKS_H}  (no circuits — the seam traps)')
        return

    body = [
        '/* GENERATED by tools/transpile.py — DO NOT EDIT.',
        ' *',
        ' * The per-circuit HOOK BODIES: the code each expansion circuit\'s patched JSR/JMPs call.',
        ' * All of it lives at $5300-$5A25, so every circuit\'s body occupies the SAME addresses and',
        ' * they can only coexist under different C names.  One function per circuit, entered by',
        ' * 6502 address (the `region` form) — see the note above collect_track_hooks() in',
        ' * tools/transpile.py, docs/phases.md §5c, and src/platform/track.h for the model.',
        ' *',
        ' * ⚠ ModifyGameCode is NOT here.  It runs once at start-up on real hardware and its effect',
        ' * is already applied as data by the installer; running it again would patch a patched image.',
        ' */',
        '#include "../cpu/cpu.h"',
        '#include "../cpu/bus.h"',
        '#include "revs_decl.h"',
        '#define REVS_MEM_ALIASES',
        '#include "mem.h"',
        '#include "../platform/platform_c.h"',
        '#include "../platform/probe.h"',
        '#include "../platform/track.h"   /* g_track — which circuit the engine is running */',
        '#include "revs_track_hooks.h"',
        '',
    ] + seam
    decl = [
        '/* GENERATED by tools/transpile.py — DO NOT EDIT.  See revs_track_hooks.c. */',
        '#ifndef REVS_TRACK_HOOKS_H',
        '#define REVS_TRACK_HOOKS_H',
        '',
        f'#define REVS_TRACK_HOOK_CIRCUITS {len(rows)}',
        '/* `inline` so a consumer that needs only one of the two (track.c needs _has, the',
        ' * generated bodies need _call) does not draw an unused-function warning. */',
        '#define REVS_HOOK_FN inline',
        '',
    ]
    for row in rows:
        decl.append(f'void trk_{row["dfs"].lower()}(unsigned short entry);'
                    f'   /* {row["disp"]} */')
    decl.append('')

    # ⭐ Register the dispatch entries so an intra-window JSR emits `trk_x(0xTTTT)` rather than a
    # call to a function name that does not exist.  Same mechanism the SMC 'call' class uses.
    for row in rows:
        for a in row['entries']:
            SMC_REGION_OF[a] = f'trk_{row["dfs"].lower()}'

    for row in rows:
        name = f'trk_{row["dfs"].lower()}'
        addrs = {i['addr'] for i in row['insns']}
        pseudo = {'start': min(addrs), 'end': max(addrs), 'name': name,
                  'insns': row['insns']}
        body.append(f'/* ---- {row["disp"]} ({row["dfs"]}) — {len(row["insns"])} instructions, '
                    f'{len(row["entries"])} entries ---- */')
        # ⚠ SMC_REGION_OF must name THIS circuit while its body is emitted: $5572 is an entry in
        # every circuit, so the map is per-circuit and is re-pointed before each pass.
        for r2 in rows:
            for a in r2['entries']:
                SMC_REGION_OF[a] = f'trk_{r2["dfs"].lower()}'
        for a in row['entries']:
            SMC_REGION_OF[a] = name
        lines = translate_func(pseudo, funcs_by_start, symbols,
                               external_entry_labels=set(),
                               external_entries=external_entries,
                               wrapper_names=wrapper_names,
                               unit_addrs=addrs,
                               dispatch_entries=row['entries'])
        # translate_func emits `void <name>(uint16_t _entry)`; the header declares it with
        # `unsigned short`, which is the same type — keep the signatures textually identical so
        # the Amiga C++ build (which has no <stdint.h>) does not see two different declarations.
        body.extend(ln.replace(f'void {name}(uint16_t _entry)',
                               f'void {name}(unsigned short _entry)') for ln in lines)

    decl += [
        '/* Does circuit `t` have a body for hook address `a`?  ⚠ Both arguments are load-bearing:',
        '   $5572 is a hook entry in every circuit and is DIFFERENT CODE in each. */',
        'static REVS_HOOK_FN int revs_track_hook_has(unsigned char t, unsigned short a)',
        '{',
        '    switch (t) {',
    ]
    for row in rows:
        cases = ' '.join(f'case 0x{a:04X}:' for a in row['entries'])
        decl += [f'    case {row["index"]}:  /* {row["disp"]} */',
                 f'        switch (a) {{ {cases} return 1; default: return 0; }}']
    decl += ['    default: return 0;',
             '    }',
             '}',
             '',
             '/* Run it.  Returns 0 if this circuit has no body at that address — the caller',
             '   reports that; it must never be treated as "nothing to do". */',
             'static REVS_HOOK_FN int revs_track_hook_call(unsigned char t, unsigned short a)',
             '{',
             '    if (!revs_track_hook_has(t, a)) return 0;',
             '    switch (t) {']
    for row in rows:
        decl.append(f'    case {row["index"]}: trk_{row["dfs"].lower()}(a); return 1;')
    decl += ['    default: return 0;',
             '    }',
             '}',
             '',
             '#endif /* REVS_TRACK_HOOKS_H */',
             '']
    OUT_HOOKS_H.write_text('\n'.join(decl))
    OUT_HOOKS.write_text('\n'.join(body) + '\n')
    tot = sum(len(r['insns']) for r in rows)
    print(f'Wrote {OUT_HOOKS}  ({len(rows)} circuits, {tot} hook instructions: '
          + ', '.join(f'{r["dfs"]}={len(r["insns"])}' for r in rows) + ')')

def main():
    symbols = load_symbols(SYM_CSV)
    write_mem_header(OUT_MEM)
    funcs, func_by_addr = parse_listing(LISTING, symbols)
    funcs_by_start = {f['start']: f for f in funcs}

    print(f'Parsed {len(funcs)} functions, '
          f'{sum(len(f["insns"]) for f in funcs)} instructions')

    # -----------------------------------------------------------------------
    # Pass 1: collect cross-function branch/JMP targets.
    # For each branch/JMP whose target T is NOT in the current function's
    # address range but IS within another function's range (and not at that
    # function's start), record T as an "external entry" needing a wrapper.
    # -----------------------------------------------------------------------
    # func_addr_ranges: list of (start, end) for range containment tests.
    func_addr_ranges = [(f['start'], f['end'], f) for f in funcs]

    # external_entries: target_addr → containing_func
    external_entries = {}
    # external_labels_for_func: func_start → set of addr needing L_xxxx labels
    external_labels_for_func = defaultdict(set)

    for func in funcs:
        for insn in func['insns']:
            mnem, op, nbytes = insn['mnem'], insn['op'], len(insn['bytes'])
            if mnem not in BRANCH_FLAGS and mnem not in ('JMP', 'JSR'):
                continue
            mode, val, _ = parse_operand(op, nbytes, symbols)
            if val == 0:
                continue
            # Is target within THIS function's range (incl. orphan prefix)?
            # A branch/JMP there is a plain local goto — but a JSR is NOT: it has to
            # return, so it needs a real C function even when the caller and callee sit
            # inside the same Ghidra function.  Revs has three such nested routines
            # (Ghidra put FUN_1DA6/FUN_1DAF inside plot_view_src_line and FUN_3273 inside
            # FUN_3261); skipping them here emitted a call to a function that was never
            # defined, which the C compiler caught — a reminder that the C type system is
            # part of this pipeline's error detection, not an obstacle to it.
            if func_lo(func) <= val <= func['end'] and mnem != 'JSR':
                continue
            # Target is outside. Find which function contains it.
            container = find_containing_func(val, funcs)
            if container is None:
                continue
            if val == container['start']:
                continue  # it's a normal tail call to another function's start
            # Mid-function entry: needs a wrapper and a label in the container.
            external_entries[val] = container
            external_labels_for_func[container['start']].add(val)

    # ⭐ THE HOOK BODIES' ENGINE EXITS ARE EXTERNAL ENTRIES TOO, and they have to be collected
    # HERE — before the wrapper fixpoint — not after.  A circuit's hook returns to the engine at
    # $2490 / $253B / $461B, which are mid-function addresses the engine itself only ever reaches
    # by falling through or branching, so they exist as `L_2490:` labels and NOT as callable C.
    # Discovering them later would emit `FUN_2490()` against a function that was never defined.
    # (The compiler would catch it — but the fix belongs here, where every other mid-function
    # entry is already handled, rather than as a special case bolted on downstream.)
    track_hooks = collect_track_hooks()
    for row in track_hooks:
        for val in row['exits']:
            if val in funcs_by_start or is_mos(val):
                continue
            container = find_containing_func(val, funcs)
            if container is None or val == container['start']:
                continue
            external_entries[val] = container
            external_labels_for_func[container['start']].add(val)

    wrapper_names = {}  # target_addr → wrapper function name
    for addr, container in external_entries.items():
        wname = symbols.get(addr, f'FUN_{addr:04x}')
        wrapper_names[addr] = wname

    # -----------------------------------------------------------------------
    # Cascading split fixpoint.
    # When a function is split at address S, code in any segment before S
    # may have branches/JMPs that target addresses inside the post-split
    # tail (i.e. >= S within the same container).  Those target addresses
    # also need to become split functions so they can be called by name.
    # Iterate until no new entries are discovered.
    # -----------------------------------------------------------------------
    def segments_for_container(c):
        """Return [(seg_start, seg_end)] for all segments of container c."""
        splits = sorted(
            a for a, cont in external_entries.items() if cont['start'] == c['start']
        )
        # First segment starts at func_lo so an absorbed orphan prefix counts
        # as part of segment 0 (a backward branch into it is intra-segment, not
        # a spurious cross-segment split).
        starts = [func_lo(c)] + splits
        ends   = splits + [c['end'] + 1]
        return list(zip(starts, ends))

    changed = True
    while changed:
        changed = False
        for container in funcs:
            for seg_start, seg_end in segments_for_container(container):
                for insn in container['insns']:
                    if insn['addr'] < seg_start:
                        continue
                    if insn['addr'] >= seg_end:
                        break
                    mnem, op, nbytes = insn['mnem'], insn['op'], len(insn['bytes'])
                    if mnem not in BRANCH_FLAGS and mnem != 'JMP':
                        continue
                    mode, target, _ = parse_operand(op, nbytes, symbols)
                    if target <= 0:
                        continue
                    # Branch/JMP from within this segment to AFTER this segment
                    # but still within the container — needs a new split point.
                    # Branch crosses segment boundary: target is in the container's
                    # range but outside the current segment (forward OR backward).
                    # Skip targets that are already Ghidra function starts — those
                    # are handled as normal tail-calls, not split wrappers.
                    in_container = func_lo(container) <= target <= container['end']
                    in_segment   = seg_start <= target < seg_end
                    already_func = target in funcs_by_start
                    if in_container and not in_segment and not already_func and target not in external_entries:
                        external_entries[target] = container
                        external_labels_for_func[container['start']].add(target)
                        wname = symbols.get(target, f'FUN_{target:04x}')
                        wrapper_names[target] = wname
                        changed = True

    # -----------------------------------------------------------------------
    # Collect all branch/JMP/JSR targets that fall in no function range.
    # Ghidra sometimes misses functions for gap addresses. Generate stubs.
    # -----------------------------------------------------------------------
    jsr_targets_unknown = set()
    all_call_mnems = set(BRANCH_FLAGS.keys()) | {'JMP', 'JSR'}
    for func in funcs:
        for insn in func['insns']:
            if insn['mnem'] not in all_call_mnems: continue
            mode, val, _ = parse_operand(insn['op'], len(insn['bytes']), symbols)
            # Indirect JMP (e.g. JMP ($E0)) is emitted as platform_indirect_jmp;
            # the pointer address ($00E0) is data, not a call target — don't stub it.
            if mode == 'jmpind': continue
            if val == 0: continue
            if val in funcs_by_start: continue
            if val in external_entries: continue
            if val in wrapper_names: continue
            # A MOS entry is an OS call, emitted as platform_mos_call() — not a routine
            # in the image, so it must never become a stub.
            if is_mos(val): continue
            # Check if it falls in any function range
            if find_containing_func(val, funcs) is not None: continue
            jsr_targets_unknown.add(val)

    # A call into ROM that is NOT a MOS entry cannot be emitted at all: there is no code
    # for it in the image and no OS semantics to service.  Revs has none (17 MOS sites and
    # nothing else — docs/static-map.md), so if one appears, the listing or the entry set
    # changed and that is worth stopping for rather than emitting an empty stub.
    rom_calls = sorted(a for a in jsr_targets_unknown if a >= ROM_BASE)
    if rom_calls:
        raise SystemExit('JSR/JMP into ROM that is not a MOS entry: '
                         + ', '.join(f'${a:04X}' for a in rom_calls)
                         + '\n  -> identify each before generating (docs/bbc-hardware.md).')

    # -----------------------------------------------------------------------
    # ⭐ Group cyclic segment groups into regions BEFORE the declarations are written: a
    # region needs its own prototype, and every name it absorbs becomes a thin wrapper.
    regions, region_of = build_regions(funcs, external_entries, symbols)
    check_split_cycles(regions, region_of, funcs, external_entries, symbols)
    # An SMC-computed JSR into a region is emitted as `region_xxxx(target)`, so the
    # emitter needs the address -> region-name map, and every computable target must
    # actually be dispatchable somewhere.
    for r in regions:
        for a in r['dispatch']:
            SMC_REGION_OF[a] = r['name']
    orphan = sorted(t for t in SMC_CALL_TARGETS
                    if t not in SMC_REGION_OF and t not in funcs_by_start
                    and t not in wrapper_names)
    if orphan:
        raise SystemExit('SMC "call" targets that are neither a region entry nor a '
                         'function start: ' + ', '.join(f'${a:04X}' for a in orphan)
                         + '\n  -> a computed JSR cannot reach them (docs/static-map.md '
                           '§Open items 10).')

    # Forward declarations header — includes wrapper function names.
    # -----------------------------------------------------------------------
    decl_lines = [
        '#ifndef REVS_DECL_H', '#define REVS_DECL_H',
        '/* Auto-generated by tools/transpile.py — do not edit */',
        '#include <stdint.h>', '',
        '/* Forward declarations for all 6502 routines */',
    ]
    for f in funcs:
        decl_lines.append(f'void {f["name"]}(void);')
        # Validated funcs: the plain name (declared above) is the native version
        # in revs_native.c; also declare the transliterated reference twin.
        if f['start'] in SPLIT_FUNCS:
            decl_lines.append(f'void {f["name"]}{VALIDATE_SUFFIX}(void);')
    # Region bodies: one C function per cyclic segment group, entered by 6502 address.
    if regions:
        decl_lines.append('')
        decl_lines.append('/* Merged loop regions (build_regions) — entered by 6502 address */')
        for r in regions:
            decl_lines.append(f'void {r["name"]}(uint16_t entry);')
    # Wrappers for mid-function entry points.
    decl_lines.append('')
    decl_lines.append('/* Wrappers for cross-function branch/JMP entry points */')
    for addr, wname in sorted(wrapper_names.items()):
        decl_lines.append(f'void {wname}(void);')
        # A validated mid-function entry: its split body is emitted under the
        # `__t6502` twin (translate_func, def_name) with the plain name native;
        # declare the twin too so the validation harness can reach it.
        if addr in SPLIT_FUNCS:
            decl_lines.append(f'void {wname}{VALIDATE_SUFFIX}(void);')
    # Stubs for unlisted JSR targets.
    decl_lines.append('')
    decl_lines.append('/* Stubs for JSR targets without a Ghidra-detected function */')
    for addr in sorted(jsr_targets_unknown):
        name = symbols.get(addr, f'FUN_{addr:04x}')
        decl_lines.append(f'void {name}(void);')
    decl_lines += ['', '#endif /* REVS_DECL_H */']
    OUT_H.write_text('\n'.join(decl_lines) + '\n')
    print(f'Wrote {OUT_H}')

    # -----------------------------------------------------------------------
    # Pass 2: generate C.
    # -----------------------------------------------------------------------
    header = [
        '/* Auto-generated by tools/transpile.py — do not edit */',
        '#include "../cpu/cpu.h"',
        '#include "../cpu/bus.h"',
        '#include "revs_decl.h"',
        '#define REVS_MEM_ALIASES  /* enable bare lvalue aliases (lap_counter = ...) */',
        '#include "mem.h"   /* MEM_<name> offsets + bare aliases for named RAM/state */',
        '#include "../platform/platform_c.h"',
        '#include "../platform/probe.h"   /* PROBE_PHASE(): main-loop phase brackets */',
        '#include "../platform/shape.h"   /* PROBE_SHAPE_*(): input-distribution counters */',
        '',
    ]
    body = []
    # ⭐ Region bodies first: one C function per cyclic segment group, entered by address.
    # Every name that used to own one of those segments becomes a thin wrapper below, so
    # callers, symbols.csv names and the main-loop phase brackets are all unchanged.
    for r in regions:
        pseudo = {'start': r['lo'], 'end': r['hi'], 'name': r['name'], 'insns': r['insns']}
        body.append(f'/* {r["name"]}: ${r["lo"]:04X}-${r["hi"]:04X} — a 6502 loop whose '
                    f'segments would otherwise tail-call each other in a cycle.  Entries: '
                    + ', '.join(f'${a:04X}' for a in r['entries']) + '.')
        body.append(f'   See build_regions() in tools/transpile.py. */')
        body.extend(translate_func(pseudo, funcs_by_start, symbols,
                                   external_entry_labels=set(),
                                   external_entries=external_entries,
                                   wrapper_names=wrapper_names,
                                   unit_addrs={i['addr'] for i in r['insns']},
                                   dispatch_entries=r['dispatch']))

    for f in funcs:
        if f['start'] in region_of:
            r = region_of[f['start']]
            nm = f['name'] + (VALIDATE_SUFFIX if f['start'] in SPLIT_FUNCS else '')
            body.append(f'void {nm}(void) {{ {r["name"]}(0x{f["start"]:04X}); }}')
            body.append('')
            continue
        ext_labels = external_labels_for_func.get(f['start'], set())
        body.extend(translate_func(f, funcs_by_start, symbols,
                                   external_entry_labels=ext_labels,
                                   external_entries=external_entries,
                                   wrapper_names=wrapper_names))

    # Stubs for JSR targets Ghidra didn't create functions for.
    if jsr_targets_unknown:
        body.append('/* === Stubs for JSR targets without a known function === */')
        body.append('/* TODO: investigate each — may be data misidentified as code. */')
        for addr in sorted(jsr_targets_unknown):
            name = symbols.get(addr, f'FUN_{addr:04x}')
            body.append(f'void {name}(void) {{ /* stub: no instructions found at ${addr:04X} */ }}')
        body.append('')

    # Emit split functions for mid-function entry points.
    # Each wrapper is the code from the entry address to the end of its
    # container function — a faithful slice, not an approximation.
    body.append('/* === Split functions for cross-function entry points === */')
    body.append('/* Each function starts at the labelled address inside its container. */')
    for addr in sorted(external_entries):
        container  = external_entries[addr]
        wname      = wrapper_names[addr]

        # This segment belongs to a region: its code lives in the region body, so the name
        # becomes a thin wrapper that enters the region at this address.
        if addr in region_of:
            r = region_of[addr]
            nm = wname + (VALIDATE_SUFFIX if addr in SPLIT_FUNCS else '')
            body.append(f'void {nm}(void) {{ {r["name"]}(0x{addr:04X}); }}')
            body.append('')
            continue

        # Build an instruction index for the container.
        insns = container['insns']
        addr_to_idx = {insn['addr']: i for i, insn in enumerate(insns)}
        start_idx   = addr_to_idx.get(addr)

        if start_idx is None:
            # Address not found as an instruction start — emit a plain comment.
            body.append(f'void {wname}(void) {{')
            body.append(f'    /* entry ${addr:04X} not found in {container["name"]} */')
            body.append(f'}}')
            body.append('')
            continue

        # Build a synthetic function dict for the slice.
        sliced_insns = insns[start_idx:]
        sliced_func  = {
            'start': addr,
            'end':   container['end'],
            'name':  wname,
            'insns': sliced_insns,
        }

        # External entry labels within the slice (strictly after addr).
        slice_ext_labels = {
            a for a in external_labels_for_func.get(container['start'], set())
            if a > addr
        }

        body.extend(translate_func(sliced_func, funcs_by_start, symbols,
                                   external_entry_labels=slice_ext_labels,
                                   external_entries=external_entries,
                                   wrapper_names=wrapper_names))

    OUT_C.write_text('\n'.join(header + body) + '\n')
    print(f'Wrote {OUT_C}  ({len(header)+len(body)} lines)')

    emit_track_hooks(track_hooks, funcs_by_start, symbols, external_entries, wrapper_names)

    # -----------------------------------------------------------------------
    # revs_smc_bytes.h — every mem[] byte the emitted C consults at RUN TIME.
    #
    # ⭐ Which bytes those are is a property of the SITE KIND, not a separate list:
    #   'opcode'  — the site address itself is the switched byte
    #   otherwise — the declared 'bytes' set (operand / branch / call all read operand bytes)
    # Deriving it here rather than writing it down twice is the point: the track installer
    # checks its patch addresses against this, so a missing SMC site becomes a loud refusal
    # instead of a circuit that quietly runs Silverstone's code (src/platform/track.h).
    # -----------------------------------------------------------------------
    smc_bytes = set()
    for addr, spec in SMC_SITES.items():
        if spec['kind'] == 'opcode':
            smc_bytes.add(addr)
        else:
            smc_bytes.update(spec.get('bytes', ()))
    smc_sorted = sorted(smc_bytes)
    smc_lines = [
        '/* GENERATED by tools/transpile.py — DO NOT EDIT.',
        ' *',
        ' * Every mem[] byte the transliteration reads at RUN TIME rather than baking into the C.',
        ' * Sorted ascending, so a lookup can bisect.  See src/platform/track.h for the one',
        ' * consumer and why it must be generated rather than written down.',
        ' */',
        '#ifndef REVS_SMC_BYTES_H',
        '#define REVS_SMC_BYTES_H',
        '',
        f'#define REVS_SMC_BYTE_COUNT {len(smc_sorted)}',
        '',
        'static const unsigned short revs_smc_bytes[REVS_SMC_BYTE_COUNT] = {',
    ]
    for i in range(0, len(smc_sorted), 12):
        smc_lines.append('    ' + ' '.join(f'0x{a:04X},' for a in smc_sorted[i:i + 12]))
    smc_lines += ['};', '']

    # ⭐ …AND THE CODE MAP, because "is this byte read at run time" has TWO answers and the list
    # above is only one of them.
    #
    # A byte the transpiler never turned into an instruction is DATA, and every data access in the
    # emitted C is a real mem[] read — `mem[(0x3500)+cpu.X]` consults mem[$3574] whatever is in
    # it.  So a circuit patching a data byte is honoured for free, and the only bytes that need an
    # SMC site are the ones inside an instruction.
    #
    # ⚠ Two circuits patch exactly that: $3574 and $35F4 (Brands, Oulton, Nürburgring), reached
    # through `mem[(0x3500)+cpu.X]` / `mem[(0x3580)+cpu.X]`.  Without this map they read as
    # unhonoured and the circuits were refused for a reason that was not true.
    code_runs = []
    for f in funcs:
        for ins in f['insns']:
            a, n = ins['addr'], len(ins['bytes'])
            code_runs.append((a, a + n - 1))
    code_runs.sort()
    merged = []
    for lo, hi in code_runs:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], hi)
        else:
            merged.append([lo, hi])
    smc_lines += [
        '/* Every byte the transpiler turned into an INSTRUCTION, as merged [lo, hi] ranges.',
        ' * Outside these the emitted C reads mem[] anyway, so a patch there needs no SMC site.',
        ' * See the note in tools/transpile.py and src/platform/track.c honoured(). */',
        f'#define REVS_CODE_RANGE_COUNT {len(merged)}',
        '',
        'static const unsigned short revs_code_ranges[REVS_CODE_RANGE_COUNT][2] = {',
    ]
    for lo, hi in merged:
        smc_lines.append(f'    {{ 0x{lo:04X}, 0x{hi:04X} }},')
    smc_lines += ['};', '', '#endif', '']
    OUT_SMC.write_text('\n'.join(smc_lines))
    print(f'Wrote {OUT_SMC}  ({len(smc_sorted)} run-time bytes, '
          f'{len(merged)} code ranges covering '
          f'{sum(h - l + 1 for l, h in merged)} bytes)')

    # -----------------------------------------------------------------------
    # revs_validate_list.h — the fixture-or-fail list (docs/validation-harness.md).
    # Emitted even when empty: the harness includes it if present, and an empty list
    # must mean "no twins yet", never "the list is stale".
    # -----------------------------------------------------------------------
    val_names = []
    for f in funcs:
        if f['start'] in VALIDATE_FUNCS:
            val_names.append(f['name'])
    for addr, wname in sorted(wrapper_names.items()):
        if addr in VALIDATE_FUNCS:
            val_names.append(wname)
    nat_names = [f['name'] for f in funcs if f['start'] in NATIVE_FUNCS]
    nat_names += [w for a, w in sorted(wrapper_names.items()) if a in NATIVE_FUNCS]
    missing = sorted(set(SPLIT_FUNCS) - {f['start'] for f in funcs} - set(wrapper_names))
    if missing:
        raise SystemExit('VALIDATE_FUNCS/NATIVE_FUNCS list addresses that are not a function '
                         'start or a mid-function entry in listing.txt: '
                         + ', '.join(f'${a:04X}' for a in missing))
    val_lines = [
        '#pragma once',
        '/* AUTO-GENERATED by tools/transpile.py from VALIDATE_FUNCS / NATIVE_FUNCS — do not edit.',
        '   Every name in either list has a native twin in src/gen/revs_native.c and a __t6502',
        '   transliteration oracle in src/gen/revs_gen.c.',
        '',
        '   VALIDATE_NAMES: tools/validate_native.c FAILS if one of these has no fixture — a',
        '   fixture-less PASS runs zero comparisons.',
        '',
        '   NATIVE_UNVALIDATED_NAMES: twins for which no fixture CAN exist (the reason is in',
        '   transpile.py next to each address).  The harness prints them on every run so the',
        '   hole stays visible; `make determinism` is what gates them.',
        '   docs/validation-harness.md */',
        'static const char* const VALIDATE_NAMES[] = {',
    ]
    val_lines += [f'    "{n}",' for n in sorted(val_names)]
    val_lines += ['    0', '};', '', 'static const char* const NATIVE_UNVALIDATED_NAMES[] = {']
    val_lines += [f'    "{n}",' for n in sorted(nat_names)]
    val_lines += ['    0', '};', '']
    OUT_VAL.write_text('\n'.join(val_lines) + '\n')
    print(f'Wrote {OUT_VAL}  ({len(val_names)} validated names, '
          f'{len(nat_names)} native without a fixture)')

    # -----------------------------------------------------------------------
    # Manual implementations stub — only when something actually needs one.
    # SMC_SITES handles all 24 self-modifying sites generically, so this file does not
    # exist by default.  Both Makefiles wildcard it, so its absence is fine.
    # -----------------------------------------------------------------------
    if MANUAL_FUNCS and not OUT_MAN.exists():
        manual = [
            '/* Hand-written implementations for routines the transliteration cannot',
            '   represent.  NOT auto-generated; edit freely.  One per MANUAL_FUNCS entry,',
            '   each with the evidence for why it cannot be transliterated.',
            '   docs/faithfulness-seam.md */',
            '#include "../cpu/cpu.h"',
            '#include "../cpu/bus.h"',
            '#include "revs_decl.h"',
            '#include <string.h>',
            '',
        ]
        for a in sorted(MANUAL_FUNCS):
            manual.append(f'/* TODO: {symbols.get(a, f"FUN_{a:04x}")} @ ${a:04X} */')
        OUT_MAN.write_text('\n'.join(manual) + '\n')
        print(f'Wrote {OUT_MAN}  (manual stubs)')
    elif OUT_MAN.exists():
        print(f'Skipped {OUT_MAN}  (already exists)')

    # -----------------------------------------------------------------------
    # Gen-time reports.  These exist so the things that bit the Atari port are visible
    # from the first generation instead of being discovered one runtime hang at a time.
    # -----------------------------------------------------------------------
    report_smc_coverage(funcs)
    report_stack_drops(funcs, symbols)
    report_brk_targets(funcs, symbols)
    report_spin_candidates(funcs, symbols)

