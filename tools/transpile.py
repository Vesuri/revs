def report_smc_coverage(funcs):
    """Every SMC_SITES address must land on a decoded instruction start, and every
    routine that contains one is named.  A site that does not match an instruction is a
    hard failure: it means the listing moved under the table (a re-import, a different
    track's runtime image) and the emitted rasteriser would be quietly wrong."""
    starts = {}
    for f in funcs:
        for ins in f['insns']:
            starts[ins['addr']] = f
    stale = sorted(a for a in SMC_SITES if a not in starts)
    if stale:
        raise SystemExit('SMC_SITES addresses are not instruction starts in listing.txt: '
                         + ', '.join(f'${a:04X}' for a in stale)
                         + '\n  -> re-check against `make sweep` (docs/static-map.md).')
    by_kind = defaultdict(int)
    for site in SMC_SITES.values():
        by_kind[site['kind']] += 1
    owners = sorted({starts[a]['name'] for a in SMC_SITES})
    print(f'SMC: {len(SMC_SITES)} patched instructions emitted as runtime-dispatched '
          f'({", ".join(f"{k}={v}" for k, v in sorted(by_kind.items()))}) '
          f'in {len(owners)} routines: {", ".join(owners)}')

def report_stack_drops(funcs, symbols):
    """The two-level RTS, audited rather than trusted.

    STACK_DROP_TXS / UNWIND_CALLEES is a hand-written table of one site, and the failure it
    guards against is silent: an unmodelled drop does not crash, it turns the road-span
    chain's exit into an infinite `plot / ADC $83 / BCC` (src/cpu/cpu.h).  So this checks
    the four things that would make the table wrong, and every one of them is fatal:

      1. each STACK_DROP_TXS address really decodes as TXS;
      2. each UNWIND_CALLEES address really is a function start (the call-site check is
         emitted per JSR target, so a mid-body address would silently emit nothing);
      3. NO OTHER `TSX / INX / INX / TXS` run exists in the image — this is the one that
         finds a second stack drop after a re-import, instead of a hang finding it;
      4. UNWIND_CALLEES are entered only by JSR.  A JMP or a cross-function conditional
         tail call into one puts the dropped frame at a different depth than the emitted
         check assumes, so the unwind would land one level off.
    """
    starts, by_addr, tgt = {}, {}, {}
    for f in funcs:
        for ins in f['insns']:
            starts[ins['addr']] = f
            by_addr[ins['addr']] = ins
            # 'val' is not a parsed field — the emitter derives it per instruction, so an
            # audit that reads ins['val'] silently sees None and passes vacuously.
            _, v, _ = parse_operand(ins['op'], len(ins['bytes']), symbols)
            tgt[ins['addr']] = v

    bad = sorted(a for a in STACK_DROP_TXS
                 if a not in by_addr or by_addr[a]['mnem'] != 'TXS')
    if bad:
        raise SystemExit('STACK_DROP_TXS addresses do not decode as TXS: '
                         + ', '.join(f'${a:04X}' for a in bad))

    func_starts = {func_lo(f) for f in funcs}
    bad = sorted(a for a in UNWIND_CALLEES if a not in func_starts)
    if bad:
        raise SystemExit('UNWIND_CALLEES addresses are not function starts: '
                         + ', '.join(f'${a:04X}' for a in bad)
                         + '\n  -> the per-JSR unwind check would emit nowhere.')

    # (3) any other TSX/INX/INX/TXS run.
    unlisted = []
    for f in funcs:
        ins = f['insns']
        for i in range(len(ins) - 3):
            if [x['mnem'] for x in ins[i:i + 4]] == ['TSX', 'INX', 'INX', 'TXS']:
                if ins[i + 3]['addr'] not in STACK_DROP_TXS:
                    unlisted.append((ins[i]['addr'], f['name']))
    if unlisted:
        raise SystemExit('UNLISTED 6502 stack drop (TSX/INX/INX/TXS) — an RTS that returns '
                         'two levels up, which the transliteration cannot express:\n'
                         + '\n'.join(f'  ${a:04X} in {n}' for a, n in unlisted)
                         + '\n  -> add its TXS to STACK_DROP_TXS and the routines that can '
                           'carry it to UNWIND_CALLEES (see src/cpu/cpu.h).')

    # (4) entry other than JSR.
    wrong_entry = []
    for f in funcs:
        for ins in f['insns']:
            if tgt[ins['addr']] not in UNWIND_CALLEES:
                continue
            mnem = ins['mnem']
            if mnem == 'JSR':
                continue
            if mnem in BRANCH_FLAGS or mnem == 'JMP':
                # A branch INSIDE the callee is just its own local flow.
                if not (func_lo(f) <= tgt[ins['addr']] <= f['end']):
                    wrong_entry.append((ins['addr'], mnem, tgt[ins['addr']], f['name']))
    if wrong_entry:
        raise SystemExit('UNWIND_CALLEES entered other than by JSR — the dropped frame '
                         'would be at a different depth than the emitted check assumes:\n'
                         + '\n'.join(f'  ${a:04X} {m} ${t:04X} in {n}'
                                     for a, m, t, n in wrong_entry))

    callers = sorted({starts[ins['addr']]['name']
                      for f in funcs for ins in f['insns']
                      if ins['mnem'] == 'JSR' and tgt[ins['addr']] in UNWIND_CALLEES})
    sites = sum(1 for f in funcs for ins in f['insns']
                if ins['mnem'] == 'JSR' and tgt[ins['addr']] in UNWIND_CALLEES)
    print(f'stack drops: {len(STACK_DROP_TXS)} two-level RTS site(s), '
          f'{sites} guarded call site(s) in {len(callers)} routines: {", ".join(callers)}')

def build_segments(funcs, external_entries, symbols):
    """Split the corpus into SEGMENTS — the units the emitter actually produces.

    A container is cut at every mid-function entry point, so what comes out of `main()` is
    already one C function per segment: `[func_lo, first_split)` for the container body, then
    `[entry, next_split)` for each split function.  Making that explicit here is what lets
    cycles among segments be found and fixed.

    Returns (segments, seg_of) where segments is {seg_start: {'lo','hi','insns','func'}} and
    seg_of(addr) -> seg_start or None.
    """
    splits = defaultdict(list)
    for addr, container in external_entries.items():
        splits[container['start']].append(addr)

    segments = {}
    for f in funcs:
        bounds = sorted(splits.get(f['start'], []))
        starts = [func_lo(f)] + bounds
        ends   = bounds + [f['end'] + 1]
        for s, e in zip(starts, ends):
            segments[s] = {'lo': s, 'hi': e - 1, 'func': f,
                           'insns': [i for i in f['insns'] if s <= i['addr'] < e]}

    ordered = sorted(segments)
    owner = {}
    for s in ordered:
        for i in segments[s]['insns']:
            owner[i['addr']] = s
    return segments, owner


def segment_graph(segments, owner, symbols):
    """Edges between segments that the emitter renders as `name(); return;`.

    ⚠ GLOBAL, not per-container.  A cycle can run through several *functions*: the $7B00
    overlay's loop is $7BF7 -> $7C00 -> $7D56 -> $7E00 -> $7EF3 -> $7BF7, and three of those
    are separate function starts, so a container-local graph sees none of it.

    A JSR is NOT an edge: it returns, so it can never form a growing chain.
    """
    terminators = {'RTS', 'RTI', 'JMP', 'BRK'}
    edges = defaultdict(set)
    for s, seg in segments.items():
        for insn in seg['insns']:
            mode, target, _ = parse_operand(insn['op'], len(insn['bytes']), symbols)
            if insn['mnem'] in BRANCH_FLAGS or insn['mnem'] == 'JMP':
                # A transfer to a segment START is a tail call; into a segment's interior it
                # is a goto, which cannot grow the stack.
                if mode != 'jmpind' and target in segments and owner.get(target) != s:
                    edges[s].add(target)
            nxt = insn['addr'] + len(insn['bytes'])
            if insn['mnem'] not in terminators and nxt in segments and owner.get(nxt) != s:
                edges[s].add(nxt)
    return edges


def strongly_connected(nodes, edges):
    """Tarjan.  Returns only the components that actually contain a cycle."""
    index, low, on_stack, stack, order, out = {}, {}, set(), [], [], []
    counter = [0]
    for root in nodes:
        if root in index:
            continue
        work = [(root, iter(sorted(edges.get(root, ()), key=str)))]
        index[root] = low[root] = counter[0]; counter[0] += 1
        stack.append(root); on_stack.add(root)
        while work:
            node, it = work[-1]
            advanced = False
            for nxt in it:
                if nxt not in index:
                    index[nxt] = low[nxt] = counter[0]; counter[0] += 1
                    stack.append(nxt); on_stack.add(nxt)
                    work.append((nxt, iter(sorted(edges.get(nxt, ()), key=str))))
                    advanced = True
                    break
                if nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop(); on_stack.discard(w); comp.append(w)
                    if w == node:
                        break
                if len(comp) > 1 or node in edges.get(node, ()):
                    out.append(sorted(comp))
    return out


def build_regions(funcs, external_entries, symbols):
    """Group every cyclic set of segments into ONE emission unit — a REGION.

    ⭐ THE FIX for the tail-call-cycle defect.  A container split at a mid-function entry is
    emitted as a separate C function reached by `name(); return;`.  That is exact for a CALL
    and ruinous for a LOOP: fall through S1..Sn, jump back to S1, and the C form is mutual
    recursion which GCC flattens on neither target — the stack grows with the iteration count
    and every iteration pays call overhead.  Two such loops shipped in every build up to
    Phase 4, one of them the per-pixel span store in plot_view_src_line.

    A region is emitted as ONE C function taking the 6502 entry address, with a `switch`
    prologue that `goto`s the right label.  Every transfer inside it is then a goto, so the
    loop is a loop.  Each entry keeps its own name as a thin wrapper, so callers and the
    profile are unchanged.  Segments in no cycle are untouched — this changes nothing about
    the ~99% of the corpus that was always fine.

    Returns (regions, region_of): regions is a list of dicts with 'name'/'entries'/'insns',
    region_of maps a segment start -> its region.
    """
    segments, owner = build_segments(funcs, external_entries, symbols)
    edges = segment_graph(segments, owner, symbols)
    comps = strongly_connected(sorted(segments), edges)

    regions, region_of = [], {}
    for comp in comps:
        insns = sorted((i for s in comp for i in segments[s]['insns']),
                       key=lambda i: i['addr'])
        # 'entries' are the SEGMENT entries (each keeps its name as a wrapper).  'dispatch'
        # additionally covers every address an SMC-computed JSR can reach inside this
        # region: those are mid-unit addresses of an unrolled chain, not segment starts, so
        # build_segments never produces them and the prologue would have no case for them.
        addrs = {i['addr'] for i in insns}
        extra = sorted(SMC_CALL_TARGETS & addrs)
        r = {'name': f'region_{comp[0]:04x}', 'entries': comp, 'insns': insns,
             'dispatch': sorted(set(comp) | set(extra)), 'smc_entries': extra,
             'lo': insns[0]['addr'], 'hi': max(i['addr'] + len(i['bytes']) - 1
                                               for i in insns)}
        regions.append(r)
        for s in comp:
            region_of[s] = r
    return regions, region_of


def check_split_cycles(regions, region_of, funcs, external_entries, symbols):
    """Verify the regions actually removed every tail-call cycle, and report what was merged.

    Runs the segment analysis again with each region collapsed to a single node.  Anything
    still cyclic would compile to unbounded mutual recursion, and that is a hard stop: it is
    invisible at runtime until it corrupts a stack.  (Before build_regions() existed this
    check could only warn, because the defect predated it — docs/static-map.md §Open items 9.)
    """
    if not regions:
        print('split-cycle check: clean (no cyclic segment groups)')
        return
    print(f'split-cycle fix: {len(regions)} 6502 loop(s) merged into single C functions with '
          f'a dispatch prologue (were cycles of tail calls — see build_regions):')
    for r in regions:
        print(f'  {r["name"]}  ${r["lo"]:04X}-${r["hi"]:04X}  '
              f'{len(r["insns"])} insn, entries: '
              + ', '.join(f'${a:04X}' for a in r['entries'])
              + (f'  (+{len(r["smc_entries"])} SMC-computed call entries)'
                 if r.get('smc_entries') else ''))

    segments, owner = build_segments(funcs, external_entries, symbols)
    edges = segment_graph(segments, owner, symbols)
    # Collapse each region to one node and re-test.
    def node(s):
        r = region_of.get(s)
        return r['name'] if r else s
    collapsed = defaultdict(set)
    for s, tgts in edges.items():
        for t in tgts:
            a, b = node(s), node(t)
            if a != b:
                collapsed[a].add(b)
    left = strongly_connected(sorted(collapsed, key=str), collapsed)
    if left:
        raise SystemExit('tail-call cycles SURVIVED region merging:\n' +
                         '\n'.join('  ' + ' -> '.join(str(x) for x in c) for c in left) +
                         '\n  -> build_regions() is not closing over the cycle; do not ship '
                         'this (docs/static-map.md §Open items 9).')
    print('  split-cycle check: clean after merging')


def report_brk_targets(funcs, symbols):
    """Report every routine whose whole body is a BRK, with its callers.

    A `JSR` to an address holding $00 is a call into memory that contains no code.  Revs
    has four such targets — $7B00, $7B4A, $7B9C, $7BE2 — reached from seven sites, and the
    page they live in is loaded by NOTHING: REVS2 covers $1200-$6FFF, a track file
    $70DB-$7814, and a real BBC has leftover front-end text there (docs/static-map.md
    §Open items).  Whether those calls are reachable is unresolved: the one measurement
    available (tools/bbc_probe_unmapped_calls.mjs) shows zero executions and zero writes
    to the page, but it also never gets past the front-end gate at $6560, which is exactly
    what stands between it and the call sites.

    Emitting them as empty functions would have made "calls into nothing" indistinguishable
    from "works".  They now trap through platform_brk(), so the first target run answers
    the question instead of hiding it."""
    lone = {}
    for f in funcs:
        if len(f['insns']) == 1 and f['insns'][0]['mnem'] == 'BRK':
            lone[f['start']] = f['name']
    if not lone:
        print('BRK targets: none')
        return
    callers = defaultdict(list)
    for f in funcs:
        for ins in f['insns']:
            if ins['mnem'] not in ('JSR', 'JMP'): continue
            m = re.match(r'^0x([0-9a-fA-F]+)$', (ins['op'] or '').strip())
            if m and int(m.group(1), 16) in lone:
                callers[int(m.group(1), 16)].append(ins['addr'])
    print(f'BRK-only targets: {len(lone)} routines that are a single $00 — calls into them '
          f'trap via platform_brk() rather than silently returning')
    for a, n in sorted(lone.items()):
        cs = ', '.join(f'${c:04X}' for c in sorted(callers.get(a, []))) or 'no callers'
        print(f'  ${a:04X} {n:<12} called from: {cs}')

def report_spin_candidates(funcs, symbols):
    """List the tight loops that are candidates for a SPINWAIT hook, instead of guessing
    at hooks up front.  A candidate is a backward branch whose whole loop body contains no
    JSR and at least one memory read — i.e. it can only exit when something ELSE changes
    memory, which under a single-threaded C port is nothing.  Reported, not hooked:
    Revs's 50 Hz body is a raster-timed User VIA T1 interrupt, so some of these are
    intra-frame waits where a platform_tick_vbi() would prevent the exit it is meant to
    enable (docs/transpiler.md §Spin-waits and hooks)."""
    cands = []
    for f in funcs:
        idx = {ins['addr']: i for i, ins in enumerate(f['insns'])}
        for i, ins in enumerate(f['insns']):
            if ins['mnem'] not in BRANCH_FLAGS: continue
            _, tgt, _ = parse_operand(ins['op'], len(ins['bytes']), symbols)
            if tgt not in idx or idx[tgt] > i: continue          # forward branch
            body = f['insns'][idx[tgt]:i + 1]
            if len(body) > 8: continue                            # not a tight spin
            if any(b['mnem'] in ('JSR', 'JMP') for b in body): continue
            reads = [b for b in body if b['mnem'] in
                     ('LDA', 'LDX', 'LDY', 'BIT', 'CMP', 'CPX', 'CPY', 'INC', 'DEC')]
            if not reads: continue
            # A loop that only touches registers is a delay, not a wait on state.
            if not any(re.search(r'0x[0-9a-f]+', b['op'] or '') for b in reads): continue
            cands.append((tgt, ins['addr'], f['name'], len(body),
                          ' ; '.join(f'{b["mnem"]} {b["op"]}'.strip() for b in body)))
    lo, hi = MAIN_LOOP_BRACKET
    for f in funcs:
        ids = [(i['addr'], i['op']) for i in f['insns']
               if lo <= i['addr'] <= hi and i['mnem'] == 'JSR']
        if not ids: continue
        print(f'main-loop phase brackets: {len(ids)} top-level calls in {f["name"]} '
              f'(${lo:04X}-${hi:04X}); phase 0 = outside the loop')
        for n, (a, op) in enumerate(ids, 1):
            tgt = int(op, 0) if op.startswith('0x') else 0
            print(f'  phase {n:2d}  ${a:04X}  -> {symbols.get(tgt, op)}')
    hooked = sorted(SPINWAIT_HOOKS)
    print(f'spin-wait candidates: {len(cands)} tight backward loops with no JSR; '
          f'{len(hooked)} HOOKED (' + ', '.join(f'${a:04X}' for a in hooked) + ')')
    for tgt, br, fname, n, txt in sorted(cands):
        mark = ' <-- HOOKED' if tgt in SPINWAIT_HOOKS else ''
        print(f'  ${tgt:04X}..${br:04X}  {fname:<28} {n} insn  {txt}{mark}')

