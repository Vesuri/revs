#!/usr/bin/env python3
"""Convert a 320x200 indexed PNG into interleaved Amiga planes and RGB4 colours.

Requires Pillow. Outputs local raw data and a C header for executable embedding.
No resizing or requantisation: reject inputs that cannot use five bitplanes.
"""
import argparse
from pathlib import Path
from PIL import Image


def convert(source):
    with Image.open(source) as image:
        if image.mode != "P" or image.size != (320, 200):
            raise ValueError("expected a 320x200 indexed PNG")
        if "transparency" in image.info:
            raise ValueError("splash must be opaque")
        pixels = bytes(image.getdata())
        if max(pixels) >= 32:
            raise ValueError("palette indices must be in 0..31")
        palette = image.getpalette()
    colours = []
    for i in range(32):
        r, g, b = ((v * 15 + 127) // 255 for v in palette[i*3:i*3+3])
        colours.append((r << 8) | (g << 4) | b)
    raw = bytearray()
    for y in range(200):
        for plane in range(5):
            for x in range(0, 320, 8):
                value = 0
                for bit in range(8):
                    value |= ((pixels[y*320+x+bit] >> plane) & 1) << (7-bit)
                raw.append(value)
    return raw, colours


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    raw, colours = convert(args.source)
    args.header.with_suffix(".raw").write_bytes(raw)
    args.header.with_suffix(".pal").write_bytes(b"".join(c.to_bytes(2, "big") for c in colours))
    lines = ["/* Generated by gen_amiga_splash.py; do not edit. */",
             "static const unsigned char kSplashData[40000] = {"]
    lines += [", ".join(f"0x{v:02x}" for v in raw[i:i+16]) + "," for i in range(0, len(raw), 16)]
    lines += ["};", "static const unsigned short kSplashPalette[32] = {",
              ", ".join(f"0x{c:03x}" for c in colours), "};", ""]
    args.header.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
