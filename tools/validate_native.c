/* The three opcodes a Y-step slot may legally hold, and the two an end-marker slot may. */
static const uint8_t STEP_OPCODES[3]   = { 0xC8, 0x88, 0xEA };   /* INY / DEY / NOP */
static const uint8_t MARKER_OPCODES[2] = { 0xE0, 0x60 };         /* CPX #$80 / RTS  */

/* How far a planted step slot moves Y, for working out which cell the call will touch. */
static int step_delta(uint8_t opcode)
{
    return opcode == 0xC8 ? 1 : opcode == 0x88 ? -1 : 0;
}

/* Plant one Y-step slot; one case in ten gets a byte the model cannot execute. */
static uint8_t plant_step(uint8_t* pre, unsigned slot)
{
    uint8_t op = (xs() % 10 == 0) ? (uint8_t)xs() : STEP_OPCODES[xs() % 3];
    pre[slot] = op;
    return op;
}

/* $2F19's per-circuit site, reached from the abandon path.  Silverstone's own bytes, an
   expansion circuit's hook, or garbage — the same three shapes build_track_geometry uses. */
static void plant_cap_smc(uint8_t* pre)
{
    unsigned shape = xs() % 10;
    if (shape < 6)      { pre[0x2F23] = 0xB9; pre[0x2F24] = 0x60; pre[0x2F25] = 0x5F; }
    else if (shape < 9) { pre[0x2F23] = 0x20; pre[0x2F24] = 0x22; pre[0x2F25] = 0x5A; }
    /* else: whatever fill_random left — the trap arm */
}

/* ⭐⭐ KEEP EVERY PLOTTER POINTER OUT OF THE I/O WINDOW, and this is a correctness fix, not
   tidiness: a random high byte puts the cell READ at $FC00-$FEFF once in about eighty cases,
   `platform_hw_read` is not a pure function of mem[], and diff_run runs the oracle first —
   so the two models legitimately read different bytes and the twin looks wrong.  (Measured:
   82 of 2000 cases, all with A or a flag differing and mem[] byte-exact.)  The engine's own
   pointers are always RAM, so holding the three high bytes below $80 measures the twin
   rather than the clock. */
static void plant_ram_pointers(uint8_t* pre)
{
    pre[0x0071] &= 0x7F;   /* plot_ptr_hi  */
    pre[0x0073] &= 0x7F;   /* plot_ptr2_hi */
    pre[0x008F] &= 0x7F;   /* plot_ptr3_hi */
    pre[0x2F50] &= 0x7F;   /* the patched destination operands, both plotters */
    pre[0x2F92] &= 0x7F;
}

/* Steer the cell the plotter is about to touch, and (sometimes) the end line it compares
   against.  `ptrCell` is the zero-page pointer the colour cell is read through. */
static void steer_plot_case(uint8_t* pre, Cpu6502* c, unsigned ptrCell, uint8_t stepIn,
                            int* emptyCell, int* abandoned)
{
    unsigned yAfter = (unsigned)((c->Y + step_delta(stepIn)) & 0xFF);
    unsigned addr   = ((unsigned)(pre[ptrCell] | (pre[(uint8_t)(ptrCell + 1)] << 8)) + yAfter)
                      & 0xFFFF;

    if (xs() % 5 == 0) { pre[0x0082] = (uint8_t)yAfter; *abandoned = 1; }   /* the abort path */
    else if (pre[0x0082] == (uint8_t)yAfter) *abandoned = 1;

    if (addr < 0xFC00 || addr >= 0xFF00) {           /* never plant into the I/O window */
        unsigned pick = xs() % 3;
        if (pick == 0) { pre[addr] = 0x00; *emptyCell = 1; }
        else if (pick == 1) pre[addr] = 0x55;
    }
}

static int test_span_leaves(void)
{
    static uint8_t pre[65536];
    unsigned liveMask = LIVE_A | LIVE_X | LIVE_Y | LIVE_S | LIVE_FLAGS;
    int fail = 0, printed = 0, t;
    int scale = 1;
    { const char* e = getenv("REVS_VALIDATE_CASES"); if (e) scale = atoi(e); }
    if (scale < 1) scale = 1;
    const int absCases = 2000 * scale, advCases = 1000 * scale,
              plotCases = 2000 * scale, markCases = 1000 * scale;

    register_fixture("abs16_math");
    register_fixture("road_span_advance");
    register_fixture("road_span_plot");
    register_fixture("road_span_plot_2");
    register_fixture("span_end_marker_p1");
    register_fixture("span_end_marker_p2");
    setenv("REVS_SMC_CONTINUE", "1", 1);

    if (want("abs16_math")) {
        int subFail = 0, negated = 0, disagreed = 0;
        for (t = 0; t < absCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            c.A = (uint8_t)xs(); c.X = (uint8_t)xs(); c.Y = (uint8_t)xs();
            /* Same trap as abs8: the `BPL` reads the CALLER's N, so a third of the cases
               decorrelate it from bit 7 of A deliberately. */
            c.N = (xs() % 3) ? (uint8_t)(c.A >> 7) : (uint8_t)(xs() & 1);
            c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            /* ⭐ D IS PINNED TO 0: the idiomatic core is a plain binary 16-bit negate, and
               abs16_math's callers are all on the per-frame driving-model / steering path.  Decimal
               mode lives ENTIRELY in race-stats / marker-draw / front-end menu, each SED…CLD
               bracketed locally (docs/static-map.md §Decimal mode, settled — the per-frame sim is
               D=0).  make determinism-drive is the empirical backstop. */
            c.D = 0;
            if (c.N != (c.A >> 7)) disagreed++;
            if (c.N) negated++;
            subFail += diff_run("abs16_math", pre, c, abs16_math, abs16_math__t6502,
                                liveMask, t, &printed);
        }
        fail += subFail;
        if (negated == 0 || disagreed == 0) {
            printf("[VACUOUS] abs16_math: %d negated, %d decorrelated of %d — "
                   "both must be non-zero\n", negated, disagreed, absCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(%d negated, %d with N vs bit 7 decorrelated, D=0 pinned)\n",
               "abs16_math", absCases, subFail, negated, disagreed);
    }

    if (want("road_span_advance")) {
        int subFail = 0, atStart = 0;
        /* The pure-C core sets only C; the transliteration also spills A/X into math_lo/math_hi
           and leaves N/Z from the restored A.  Both are 6502 implementation detail — the one
           computed fact is the carry — so drop N/V/Z and ignore the two scratch cells. */
        static const uint16_t ig[] = { 0x0074, 0x0075 };
        unsigned mask = LIVE_A | LIVE_X | LIVE_Y | LIVE_C;
        set_ignore(ig, 2);
        for (t = 0; t < advCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            c.A = (uint8_t)xs(); c.X = (uint8_t)xs(); c.Y = (uint8_t)xs();
            pre[0x0085] = (uint8_t)xs();
            /* The whole routine is one compare, so its EQUAL case has to be planted or it
               happens once in 256 and the CLC is never exercised. */
            if (xs() % 3 == 0) pre[0x3900 + pre[0x0085]] = c.Y;
            if (pre[0x3900 + pre[0x0085]] == c.Y) atStart++;
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            subFail += diff_run("road_span_advance", pre, c, road_span_advance,
                                road_span_advance__t6502, mask, t, &printed);
        }
        set_ignore(0, 0);
        fail += subFail;
        if (atStart == 0) {
            printf("[VACUOUS] road_span_advance: no case reached the block's first line\n");
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+C  "
               "(%d on the block boundary)\n",
               "road_span_advance", advCases, subFail, atStart);
    }

    {
        struct { const char* name; void (*nat)(void); void (*ref)(void);
                 unsigned ptrCell, stepIn, stepOut; } plotters[2] = {
            { "road_span_plot",   road_span_plot,   road_span_plot__t6502,
              0x0072, 0x2F47, 0x2F60 },
            { "road_span_plot_2", road_span_plot_2, road_span_plot_2__t6502,
              0x0070, 0x2F89, 0x2FA2 },
        };
        int p;
        /* bearing_lo ($8A) is the DDA accumulator's 6502 parking slot, written every call by the
           transliteration and never by the pure-C core; math_lo ($74) is the abandon-cap's flatten
           spill (FUN_2f19).  Both are implementation detail — ignore them. */
        static const uint16_t ig[] = { 0x008A, 0x0074 };
        for (p = 0; p < 2; p++) {
            int subFail = 0, empty = 0, abandoned = 0, nearTop = 0;
            if (!want(plotters[p].name)) continue;
            set_ignore(ig, 2);
            for (t = 0; t < plotCases; t++) {
                Cpu6502 c = zero_cpu();
                uint8_t stepIn;
                int isEmpty = 0, isAbandon = 0;
                unsigned mask;
                fill_random(pre);
                c.A = (uint8_t)xs(); c.X = (uint8_t)(xs() % 4); c.Y = (uint8_t)xs();
                if (xs() % 2) { c.Y = (uint8_t)(xs() % 0x2C); nearTop++; }
                plant_ram_pointers(pre);
                stepIn = plant_step(pre, plotters[p].stepIn);
                plant_step(pre, plotters[p].stepOut);
                plant_cap_smc(pre);
                steer_plot_case(pre, &c, plotters[p].ptrCell, stepIn, &isEmpty, &isAbandon);
                empty += isEmpty; abandoned += isAbandon;
                c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
                c.D = 0;
                /* On abandon the plotter's caller unwinds immediately, so A/X/Y/C are all dead
                   (the transliteration's TSX/INX clobbers X and DEY changes Y).  On every other
                   path A=accumulator, X=column, Y=stepped, C=carry all stand — N/V/Z do not. */
                mask = isAbandon ? LIVE_NONE : (LIVE_A | LIVE_X | LIVE_Y | LIVE_C);
                subFail += diff_run(plotters[p].name, pre, c, plotters[p].nat,
                                    plotters[p].ref, mask, t, &printed);
            }
            set_ignore(0, 0);
            fail += subFail;
            if (empty == 0 || abandoned == 0 || nearTop == 0) {
                printf("[VACUOUS] %s: %d empty cells, %d abandons, %d near the top of %d — "
                       "all three arms must be reached\n",
                       plotters[p].name, empty, abandoned, nearTop, plotCases);
                fail++;
            }
            printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXYC (none on abandon)  "
                   "(%d empty cell, %d abandoned the chain, %d below line $2C)\n",
                   plotters[p].name, plotCases, subFail, empty, abandoned, nearTop);
        }
    }

    {
        struct { const char* name; void (*nat)(void); void (*ref)(void);
                 unsigned slot, ptrCell; } markers[2] = {
            { "span_end_marker_p1", span_end_marker_p1, span_end_marker_p1__t6502,
              0x2FC0, 0x0070 },
            { "span_end_marker_p2", span_end_marker_p2, span_end_marker_p2__t6502,
              0x2FD7, 0x0072 },
        };
        int m;
        /* The pure-C marker sets colMark ($80) and carry (0) on the work path and touches
           nothing on RTS; A is preserved and Y only read.  N/V/Z are CPX detail, so drop them. */
        unsigned mask = LIVE_A | LIVE_X | LIVE_Y | LIVE_C;
        for (m = 0; m < 2; m++) {
            int subFail = 0, live = 0, wrote = 0;
            if (!want(markers[m].name)) continue;
            for (t = 0; t < markCases; t++) {
                Cpu6502 c = zero_cpu();
                uint8_t op = (xs() % 10 == 0) ? (uint8_t)xs() : MARKER_OPCODES[xs() % 2];
                fill_random(pre);
                plant_ram_pointers(pre);
                pre[markers[m].slot] = op;
                c.A = (uint8_t)xs(); c.Y = (uint8_t)xs();
                if (xs() % 2) c.Y = (uint8_t)(xs() % 0x2C);
                /* X == $80 is "this column never plotted", the only value that writes a
                   terminator — a uniform byte reaches it once in 256. */
                c.X = (xs() % 3) ? 0x80 : (uint8_t)xs();
                pre[0x0085] = (uint8_t)xs();
                if (op == 0xE0) live++;
                if (op == 0xE0 && c.X == 0x80) wrote++;
                c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
                c.D = 0;
                subFail += diff_run(markers[m].name, pre, c, markers[m].nat,
                                    markers[m].ref, mask, t, &printed);
            }
            fail += subFail;
            if (live == 0 || wrote == 0 || live == markCases) {
                printf("[VACUOUS] %s: %d live of %d cases, %d reached the terminator — "
                       "both opcode shapes and both X arms must run\n",
                       markers[m].name, live, markCases, wrote);
                fail++;
            }
            printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXYC  "
                   "(%d switched on, %d reached the terminator)\n",
                   markers[m].name, markCases, subFail, live, wrote);
        }
    }

    unsetenv("REVS_SMC_CONTINUE");
    return fail;
}


/* ==========================================================================
   $2D17 / $2D9A / $2E20 / $2E99 — THE FOUR SPAN-WALK ARMS
   --------------------------------------------------------------------------
   Each is an eight-column chain, unrolled once and entered partway through by a computed
   jump, looping one scan line at a time until plot_ptr2_hi reaches its bound.

   ⚠⚠ A RANDOM PRE-STATE DOES NOT TERMINATE HERE, and that is the fixture's main job:
     * the entry offset is a branch target.  A random byte is a branch to the middle of an
       instruction — which the oracle traps on too, so it is a legal case and one in eight is
       planted deliberately — but a byte that lands BACKWARD inside the chain makes the oracle
       spin forever.  The eight legal offsets come out of the image's own tables.
     * the two Y-step slots must be the SAME direction.  Opposite ones make Y oscillate, so
       the abandon test (Y == the span's end line) is never reached.
     * plot_ptr2_hi starts within a few lines of the bound, or the walk runs 256 scan lines of
       eight plots each.
     * the STEEP arms repeat a column until the DDA carries, so their delta is held above $20:
       with a random small one that inner loop runs 256 times per column per line.
   None of this weakens the comparison — it is what makes there BE one.
   ========================================================================== */
void draw_span_shallow_fwd(void);
void draw_span_shallow_fwd__t6502(void);
void draw_span_shallow_rev(void);
void draw_span_shallow_rev__t6502(void);
void draw_span_steep_fwd(void);
void draw_span_steep_fwd__t6502(void);
void draw_span_steep_rev(void);
void draw_span_steep_rev__t6502(void);

/* The image's own entry-offset tables — the eight values each arm's phase index can produce. */
static const uint8_t ARM_OFF_SHALLOW_FWD[8] = { 0x08,0x13,0x1E,0x29,0x39,0x44,0x4F,0x5A };
static const uint8_t ARM_OFF_SHALLOW_REV[8] = { 0x5A,0x4F,0x44,0x39,0x29,0x1E,0x13,0x08 };
static const uint8_t ARM_OFF_STEEP_FWD[8]   = { 0x00,0x0B,0x16,0x21,0x2E,0x39,0x44,0x4F };
static const uint8_t ARM_OFF_STEEP_REV[8]   = { 0x4F,0x44,0x39,0x2E,0x21,0x16,0x0B,0x00 };

static int test_span_arms(void)
{
    static uint8_t pre[65536];
    /* ⭐ LIVE_NONE — validate the DRAWN RESULT (mem[]), not the exit ABI.  span_walk is now
       pure C: it takes the phase and start line as arguments and returns nothing, and its exit
       A/X/Y/S/flags are dead at every real call site.  interp_edge__t6502 (the sole caller of
       the draw_span_* oracles) overwrites A with `LDA span_swapped` and reloads X/Y from the
       saved point indices the instant each arm returns, so no register these arms leave is ever
       read.  Comparing them would validate an implementation detail; the pixels are what count. */
    unsigned liveMask = LIVE_NONE;
    int fail = 0, printed = 0, t, a;
    int scale = 1;
    { const char* e = getenv("REVS_VALIDATE_CASES"); if (e) scale = atoi(e); }
    if (scale < 1) scale = 1;
    const int armCases = 400 * scale;

    struct Arm {
        const char* name; void (*nat)(void); void (*ref)(void);
        unsigned table; const uint8_t* offsets; int rev, steep; uint8_t bound;
    } arms[4] = {
        { "draw_span_shallow_fwd", draw_span_shallow_fwd, draw_span_shallow_fwd__t6502,
          0x3E50, ARM_OFF_SHALLOW_FWD, 0, 0, 0x44 },
        { "draw_span_shallow_rev", draw_span_shallow_rev, draw_span_shallow_rev__t6502,
          0x40D0, ARM_OFF_SHALLOW_REV, 1, 0, 0x2F },
        { "draw_span_steep_fwd",   draw_span_steep_fwd,   draw_span_steep_fwd__t6502,
          0x3ED0, ARM_OFF_STEEP_FWD,   0, 1, 0x44 },
        { "draw_span_steep_rev",   draw_span_steep_rev,   draw_span_steep_rev__t6502,
          0x3ED8, ARM_OFF_STEEP_REV,   1, 1, 0x2F },
    };

    for (a = 0; a < 4; a++) register_fixture(arms[a].name);
    setenv("REVS_SMC_CONTINUE", "1", 1);

    /* The descending arms' cap is the transliterated FUN_2f12→FUN_2f19 in the oracle, which
       spills through math_lo ($74) on its off-axis flatten; the pure-C span_walk_cap does not.
       That one scratch cell is the only mem[] divergence — ignore it (harmless on the fwd arms,
       which never reach the cap). */
    static const uint16_t ig[] = { 0x0074 };
    set_ignore(ig, 1);

    for (a = 0; a < 4; a++) {
        int subFail = 0, midChain = 0, trapped = 0, multiLine = 0, markerTrap = 0,
            carryIn = 0;
        if (!want(arms[a].name)) continue;
        for (t = 0; t < armCases; t++) {
            Cpu6502 c = zero_cpu();
            uint8_t step = (xs() & 1) ? 0xC8 : 0x88;      /* INY or DEY, the SAME both ends */
            unsigned phase = xs() % 8;
            int lines = 1 + (int)(xs() % 4);
            fill_random(pre);
            plant_ram_pointers(pre);
            plant_cap_smc(pre);

            pre[0x2F47] = pre[0x2F60] = pre[0x2F89] = pre[0x2FA2] = step;
            /* ⭐ One case in six plants a marker opcode the model cannot execute.  Without it
               three sabotages SURVIVED: on the steep arms an end marker is a NO-OP by
               construction (X is always a column 0-3 there, never the $80 that writes a
               terminator, and its `LDX #$80 / CLC` tail is overwritten by the loop test), so
               only the TRAP distinguishes an arm that calls one from an arm that does not. */
            { int trapMarker = (xs() % 6 == 0);
              uint8_t mop = trapMarker ? 0x12 : ((xs() & 1) ? 0xE0 : 0x60);
              pre[0x2FC0] = pre[0x2FD7] = mop;
              if (trapMarker) markerTrap++; }

            /* The three screen pointers as interp_edge would leave them: page-aligned inside
               the view's source blocks, with plot_ptr3 one page up.  ⚠ Random ones let a
               plotter store land on plot_ptr2_hi itself, and the walk then runs 256 scan
               lines instead of the four this case is trying to measure. */
            pre[0x0070] = pre[0x0072] = pre[0x008E] = 0x00;
            /* ...and both plotters' patched destinations at a real surface_edge buffer, for
               the same reason. */
            pre[0x2F4F] = pre[0x2F91] = 0x54;
            pre[0x2F50] = pre[0x2F92] = 0x05;

            /* One case in eight plants an offset that is not an instruction boundary, so the
               trap arm is tested rather than avoided; both models must take it. */
            if (xs() % 8 == 0) { pre[arms[a].table + phase] = 0xFF; trapped++; }
            else               { pre[arms[a].table + phase] = arms[a].offsets[phase];
                                 if (arms[a].offsets[phase] != arms[a].offsets[0]) midChain++; }

            /* ⭐ One ASCENDING case in twelve starts ABOVE its bound, and it is the only way
               the DDA's carry-in is ever 1: the loop test is `CPX #bound`, and its carry
               reaches the first `ADC` of the next line.  Below the bound — which is the only
               shape the game itself produces, since interp_edge derives plot_ptr_hi from a
               block index under $28 — that carry is always 0, and a twin that hard-codes it
               PASSES.  The walk then runs the long way round to the bound, which is why it is
               one case in twelve and not one in two. */
            if (!arms[a].rev && xs() % 12 == 0) {
                pre[0x0073] = (uint8_t)(arms[a].bound + 1 + (xs() % 3));
                carryIn++;
            } else {
                pre[0x0073] = (uint8_t)(arms[a].rev ? arms[a].bound + lines
                                                    : arms[a].bound - lines);
            }
            pre[0x0071] = pre[0x0073];
            pre[0x008F] = (uint8_t)(pre[0x0073] + 1);
            if (lines > 1) multiLine++;
            pre[0x0083] = (uint8_t)(0x20 + xs() % 0xC0);   /* both deltas well away from 0 */
            pre[0x0084] = (uint8_t)(0x20 + xs() % 0xC0);
            pre[0x0085] = (uint8_t)(xs() % 0x2C);          /* the source block */

            c.A = (uint8_t)xs(); c.X = (uint8_t)phase; c.Y = (uint8_t)(xs() % 0x50);
            /* Half the cases guarantee the abandon path: the end line is an even number of
               single steps away, and both slots step the same way. */
            if (xs() & 1)
                pre[0x0082] = (uint8_t)(c.Y + (step == 0xC8 ? 2 : -2) * (1 + (int)(xs() % 6)));
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            subFail += diff_run(arms[a].name, pre, c, arms[a].nat, arms[a].ref,
                                liveMask, t, &printed);
        }
        fail += subFail;
        if (midChain == 0 || trapped == 0 || multiLine == 0 || markerTrap == 0
            || (!arms[a].rev && carryIn == 0)) {
            printf("[VACUOUS] %s: %d mid-chain entries, %d trap offsets, %d multi-line, "
                   "%d marker traps, %d carry-in of %d — all must be non-zero\n",
                   arms[a].name, midChain, trapped, multiLine, markerTrap, carryIn, armCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=none  "
               "(%d entered mid-chain, %d trap offsets, %d ran >1 scan line, "
               "%d unexecutable markers, %d with a carry into the DDA)\n",
               arms[a].name, armCases, subFail, midChain, trapped, multiLine, markerTrap,
               carryIn);
    }

    set_ignore(0, 0);
    unsetenv("REVS_SMC_CONTINUE");
    return fail;
}


/* ==========================================================================
   $2B26 interp_edge, $1933 edge_x_offscreen, $193E fill_line_attr,
   $19AF draw_surface_spans, $1A98 mark_line_surfaces — THE REST OF THE ROAD PASS
   --------------------------------------------------------------------------
   interp_edge is the span rasteriser's setup and the three others are draw_road's stages.
   All but edge_x_offscreen drive the whole subtree below them, so a randomised pre-state
   exercises far more code than the twin — which is the point, and also why the pre-state has
   to be steered into a shape that TERMINATES.  `plant_span_world` is that shape: the four
   entry tables as the image holds them, both plotters' destinations at a real surface_edge
   buffer, page-aligned screen pointers, and the per-circuit sites at Silverstone's own bytes
   or a hook.  Everything the routines themselves compute is left random.
   ========================================================================== */
void interp_edge(void);
void interp_edge__t6502(void);
void edge_x_offscreen(void);
void edge_x_offscreen__t6502(void);
void fill_line_attr(void);
void fill_line_attr__t6502(void);
void draw_surface_spans(void);
void draw_surface_spans__t6502(void);
void mark_line_surfaces(void);
void mark_line_surfaces__t6502(void);

static void plant_span_world(uint8_t* pre)
{
    memcpy(pre + 0x3E50, ARM_OFF_SHALLOW_FWD, 8);
    memcpy(pre + 0x40D0, ARM_OFF_SHALLOW_REV, 8);
    memcpy(pre + 0x3ED0, ARM_OFF_STEEP_FWD,   8);
    memcpy(pre + 0x3ED8, ARM_OFF_STEEP_REV,   8);
    pre[0x2F4F] = pre[0x2F91] = 0x54;          /* surface_edge_0 — a real destination */
    pre[0x2F50] = pre[0x2F92] = 0x05;
    pre[0x0070] = pre[0x0072] = pre[0x008E] = 0x00;
    pre[0x0071] = pre[0x0073] = 0x40;
    pre[0x008F] = 0x41;
    pre[0x2F47] = pre[0x2F60] = pre[0x2F89] = pre[0x2FA2] = 0xC8;
    pre[0x2FC0] = pre[0x2FD7] = 0xE0;
    pre[0x1971] = 0x04;                        /* line_attr's fixed page */
    plant_cap_smc(pre);
}

/* $1946 — fill_line_attr's per-circuit site: Silverstone's own call, a circuit hook, or
   garbage so the trap arm is tested. */
static void plant_line_attr_smc(uint8_t* pre)
{
    unsigned shape = xs() % 10;
    if (shape < 7)      { pre[0x1946] = 0x20; pre[0x1947] = 0x33; pre[0x1948] = 0x19; }
    else if (shape < 9) { pre[0x1946] = 0x20; pre[0x1947] = 0x22; pre[0x1948] = 0x5A; }
    else                  pre[0x1946] = (uint8_t)xs();
}

static int test_road_pass(void)
{
    static uint8_t pre[65536];
    /* edge_x_offscreen / fill_line_attr / mark_line_surfaces return a real value to draw_road
       in a register or a flag — their caller reads it, so the exit ABI is validated. */
    unsigned liveMask = LIVE_A | LIVE_X | LIVE_Y | LIVE_S | LIVE_FLAGS;
    /* ⭐ interp_edge's CARRY is now an explicit argument and its exit A and flags are dead, so
       what remains live is only X and Y — and those are not a computed result: they are the
       caller's own far/near indices, restored so the transliterated caller can step them.  A
       is validated as dead, the flags too; the RESULT is mem[] + the hw/mos traces. */
    const unsigned liveEdge = LIVE_X | LIVE_Y;
    /* ⭐ draw_surface_spans returns NOTHING: its caller (draw_road) never reads its exit
       A/X/Y/flags, so the whole exit register state is an implementation detail. */
    const unsigned liveNone = LIVE_NONE;
    int fail = 0, printed = 0, t;
    int scale = 1;
    { const char* e = getenv("REVS_VALIDATE_CASES"); if (e) scale = atoi(e); }
    if (scale < 1) scale = 1;
    const int offCases = 2000 * scale, interpCases = 600 * scale,
              attrCases = 800 * scale, spanCases = 300 * scale, markCases = 800 * scale;

    register_fixture("edge_x_offscreen");
    register_fixture("interp_edge");
    register_fixture("fill_line_attr");
    register_fixture("draw_surface_spans");
    register_fixture("mark_line_surfaces");
    setenv("REVS_SMC_CONTINUE", "1", 1);

    if (want("edge_x_offscreen")) {
        int subFail = 0, off = 0;
        for (t = 0; t < offCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            c.A = (uint8_t)xs(); c.X = (uint8_t)xs(); c.Y = (uint8_t)xs();
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = (uint8_t)(xs() % 4 == 0);
            if ((uint8_t)(pre[0x5E90 + c.X] + 0x14) >= 0x28) off++;
            subFail += diff_run("edge_x_offscreen", pre, c, edge_x_offscreen,
                                edge_x_offscreen__t6502, liveMask, t, &printed);
        }
        fail += subFail;
        if (off == 0 || off == offCases) {
            printf("[VACUOUS] edge_x_offscreen: %d of %d off axis — both answers must occur\n",
                   off, offCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  (%d off axis)\n",
               "edge_x_offscreen", offCases, subFail, off);
    }

    if (want("interp_edge")) {
        int subFail = 0, drew = 0, published = 0, swapped = 0, solid = 0;
        for (t = 0; t < interpCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            plant_span_world(pre);
            /* The endpoint's x decides whether a span is drawn at all: the block index it
               yields has to stay under $28, which is x in $30..$CF.  Two thirds of the cases
               are inside that window and the rest test the "off the side" exit. */
            if (xs() % 3) pre[0x007E] = (uint8_t)(0x30 + xs() % 0xA0);
            /* ⭐ Steer a handful of cases onto the block==$28 boundary ($7E in $D0..$D3), the
               tightest off-side value.  The 6502 test is CMP #$28 / BCS (>= $28); the fixed PRNG
               stream never rolls this exact window on its own, so the sabotage that weakens the
               test to > $28 would otherwise survive as a pure coverage gap. */
            if (t % 40 == 0) pre[0x007E] = (uint8_t)(0xD0 + (xs() & 3));
            pre[0x0083] = (uint8_t)(0x20 + xs() % 0xC0);
            pre[0x0084] = (uint8_t)(0x20 + xs() % 0xC0);
            pre[0x0027] = (uint8_t)(xs() % 4);          /* the pass number */
            pre[0x004B] = (uint8_t)(xs() % 0x50);       /* the side's end cursor */
            pre[0x004F] = (uint8_t)(xs() % 0x50);
            pre[0x007F] = (uint8_t)(xs() % 0x50);       /* the span's start line */
            c.A = (uint8_t)(xs() % 0x20);               /* the style record index */
            /* ⭐ A style whose first byte is $00 is the "all four columns" case: the routine
               substitutes $55 and WRITES IT BACK into the record.  With a random byte that
               happens twice in 600 and the sabotage that drops the substitution PASSED. */
            if (xs() % 8 == 0) { pre[0x5FD0 + c.A] = 0x00; solid++; }
            c.X = (uint8_t)(xs() % 0x50);
            c.Y = (uint8_t)(xs() % 0x50);
            pre[0x5F20 + c.Y] = (uint8_t)(xs() % 0x60);
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1;
            c.C = (uint8_t)(xs() % 4 == 0);             /* the publish-only argument */
            c.D = 0;
            if (c.C) published++;
            /* ⚠ The oracle (interp_edge__t6502) still does PHP on entry to capture the caller's
               carry; the twin takes it as a parameter and never touches the stack.  The only
               mem[] that PHP writes is the one 6502-stack byte at $01FF, which nothing reads —
               ignore it so the RESULT is compared, not a dead push. */
            { static const uint16_t ig[] = { 0x01FF }; set_ignore(ig, 1); }
            subFail += diff_run("interp_edge", pre, c, interp_edge, interp_edge__t6502,
                                liveEdge, t, &printed);
            set_ignore(0, 0);
            if (mem[0x0085] < 0x28 && !c.C) drew++;
            if (mem[0x001E] & 0x80) swapped++;
        }
        fail += subFail;
        if (drew == 0 || published == 0 || swapped == 0 || solid == 0) {
            printf("[VACUOUS] interp_edge: %d drew, %d publish-only, %d swapped, %d solid of "
                   "%d — all four must be non-zero\n",
                   drew, published, swapped, solid, interpCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=XY ($01FF ignored)  "
               "(%d reached a span walk, %d publish-only, %d swapped the endpoints, "
               "%d solid patterns)\n",
               "interp_edge", interpCases, subFail, drew, published, swapped, solid);
    }

    if (want("fill_line_attr")) {
        int subFail = 0, clamped = 0, marked = 0;
        for (t = 0; t < attrCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            plant_span_world(pre);
            plant_line_attr_smc(pre);
            { int i; for (i = 0; i < 0x50; i++) pre[0x5F20 + i] = (uint8_t)(xs() % 0x60); }
            pre[0x001F] = (uint8_t)(xs() % 0x50);       /* horizon_extent — the start line */
            pre[0x0050] = (uint8_t)(xs() % 0x50);       /* road_split_index */
            c.A = (xs() & 1) ? 0x00 : 0x50;             /* which line_attr buffer */
            c.Y = (uint8_t)(xs() % 0x50);               /* the side's end cursor */
            c.X = (uint8_t)(xs() % 0x50);               /* the first edge point */
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            subFail += diff_run("fill_line_attr", pre, c, fill_line_attr,
                                fill_line_attr__t6502, liveMask, t, &printed);
            if (mem[0x007F] == 0) clamped++;
            { int i, m = 0;
              for (i = 0; i < 0x50; i++) if (mem[0x5EE0 + i] & 0x80) m++;
              if (m) marked++; }
        }
        fail += subFail;
        if (clamped == 0 || marked == 0) {
            printf("[VACUOUS] fill_line_attr: %d clamped, %d marked a point of %d\n",
                   clamped, marked, attrCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(%d filled to line 0, %d marked at least one point)\n",
               "fill_line_attr", attrCases, subFail, clamped, marked);
    }

    if (want("draw_surface_spans")) {
        int subFail = 0, ran = 0, movedSplit = 0;
        for (t = 0; t < spanCases; t++) {
            Cpu6502 c = zero_cpu();
            uint8_t splitBefore;
            fill_random(pre);
            plant_span_world(pre);
            { int i; for (i = 0; i < 0x50; i++) pre[0x5F20 + i] = (uint8_t)(xs() % 0x60); }
            pre[0x004B] = (uint8_t)(4 + xs() % 0x14);   /* a short walk, or it is minutes */
            /* ⭐ Half the cases put road_split_index exactly where the walk will arrive:
               the "at the split" arm is a single index out of the whole walk, and with a
               uniform value it ran 6 times in 300. */
            pre[0x0050] = (uint8_t)(xs() % 0x18);
            pre[0x0032] = (uint8_t)(xs() % 0x20);
            pre[0x008C] = (uint8_t)(xs() % 0x20);
            pre[0x007E] = (uint8_t)(0x30 + xs() % 0xA0);
            pre[0x007F] = (uint8_t)(xs() % 0x50);
            pre[0x0083] = (uint8_t)(0x20 + xs() % 0xC0);
            pre[0x0084] = (uint8_t)(0x20 + xs() % 0xC0);

            c.Y = (uint8_t)(xs() % 4);                  /* the pass */
            c.A = (uint8_t)(xs() % 0x10);               /* the first edge index */
            if (xs() & 1) pre[0x0050] = (uint8_t)(c.A + xs() % 6);
            c.X = (uint8_t)xs();
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            splitBefore = pre[0x0050];
            subFail += diff_run("draw_surface_spans", pre, c, draw_surface_spans,
                                draw_surface_spans__t6502, liveNone, t, &printed);
            if (c.A < pre[0x004B]) ran++;
            if (mem[0x0050] != splitBefore) movedSplit++;
        }
        fail += subFail;
        if (ran == 0 || movedSplit == 0) {
            printf("[VACUOUS] draw_surface_spans: %d walked, %d moved the split of %d\n",
                   ran, movedSplit, spanCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=none  "
               "(%d ran the walk, %d moved road_split_index)\n",
               "draw_surface_spans", spanCases, subFail, ran, movedSplit);
    }

    if (want("mark_line_surfaces")) {
        int subFail = 0, walked = 0, stamped = 0;
        for (t = 0; t < markCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            { int i; for (i = 0; i < 0x60; i++) pre[0x5F20 + i] = (uint8_t)(xs() % 0x60); }
            /* Past $28 the routine does nothing but compute its return value, and that arm
               is one case in four rather than 216 in 256. */
            pre[0x62F2] = (xs() % 4) ? (uint8_t)(xs() % 0x28) : (uint8_t)(0x28 + xs() % 0xD8);
            pre[0x004B] = (uint8_t)(1 + xs() % 0x30);
            pre[0x0050] = (uint8_t)(xs() % 0x50);
            c.X = (xs() & 1) ? 0x04 : 0x14;             /* the surface class */
            c.A = (uint8_t)(xs() % 0x28);               /* the first edge point */
            c.Y = (uint8_t)xs();
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            if (pre[0x62F2] < 0x28) walked++;
            subFail += diff_run("mark_line_surfaces", pre, c, mark_line_surfaces,
                                mark_line_surfaces__t6502, liveMask, t, &printed);
            { int i, n = 0;
              for (i = 0; i < 0x50; i++) if (mem[0x5F60 + i]) n++;
              if (n) stamped++; }
        }
        fail += subFail;
        if (walked == 0 || walked == markCases || stamped == 0) {
            printf("[VACUOUS] mark_line_surfaces: %d walked, %d stamped of %d — the skip arm "
                   "and the walk must both run\n", walked, stamped, markCases);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(%d below 45 degrees, %d left a class behind)\n",
               "mark_line_surfaces", markCases, subFail, walked, stamped);
    }

    unsetenv("REVS_SMC_CONTINUE");
    return fail;
}

/* ==========================================================================
   TWINS #40-#43 — THE VIEW/DASHBOARD SEAM'S CALLEES
   --------------------------------------------------------------------------
   $1E9E surface_colour_at, $1DAF column_gap_walk, $1DA6 fill_column_gaps and
   $1DEF fill_edge_column_run.  Three things have to be steered or the cases land on
   nothing:

   1. surface_colour_at IS SIX ARMS AND A UNIFORM BYTE PICKS ONE.  The horizon test alone
      sends half the cases straight out, and the four boundary compares are nested, so the
      innermost arm (the line's own background) needs all four to fall through — about one
      case in sixteen by luck.  The fixture pins the line below the horizon in most cases and
      COUNTS which arm each case took, so a zero is a failure and not a silent gap.

   2. column_gap_walk'S BRANCH OFFSET IS AN OPCODE-LEVEL INPUT.  $1DD5 is a branch offset the
      caller plants; only $09 and $EF are arms the engine ever uses, and the twin traps on
      anything else.  Both arms and the trap are exercised, and the trap has to trap in BOTH
      models (the oracle's switch has a `default:` for exactly this).

   3. THE POINTER IT STORES THROUGH CAN BE ANYTHING under fill_random, including page zero and
      the hardware window — and the oracle re-reads that pointer at every store, so a hoisted
      base is only correct while the walk cannot reach it.  Both cases are planted on purpose:
      the game's own pointers ($70/$72) and a random zero-page number.
   ========================================================================== */
void surface_colour_at(void);
void surface_colour_at__t6502(void);
void column_gap_walk(void);
void column_gap_walk__t6502(void);
void fill_column_gaps(void);
void fill_column_gaps__t6502(void);
void fill_edge_column_run(void);
void fill_edge_column_run__t6502(void);

#define PRE_HORIZON_EXTENT 0x001F
#define PRE_EDGE_COLUMN    0x0085
#define PRE_BLOCK_START    0x0082
#define PRE_LINE_CURSOR    0x007F
#define PRE_GAP_BRANCH     0x1DD5
#define PRE_GAP_FALLBACK   0x1DDC
#define PRE_GAP_POINTER    0x1DDE

/* Which of surface_colour_at's six arms a case takes, decided from the PRE state — nothing
   the routine calls writes any of these cells. */
enum { SC_SKY = 0, SC_EDGE0, SC_ATTR1, SC_EDGE3, SC_ATTR0, SC_INSIDE, SC_ARMS };
static int surface_arm(const uint8_t* pre, uint8_t line)
{
    unsigned pos = pre[PRE_EDGE_COLUMN];
    if (line > pre[PRE_HORIZON_EXTENT])       return SC_SKY;
    if (pos >= pre[0x0554 + line])            return SC_EDGE0;
    if (pos >= pre[0x0600 + line])            return SC_ATTR1;
    if (pos >= pre[0x0650 + line])            return SC_EDGE3;
    if (pos >= pre[0x05A4 + line])            return SC_ATTR0;
    return SC_INSIDE;
}

static int test_seam_callees(void)
{
    static uint8_t pre[65536];
    unsigned liveMask = LIVE_A | LIVE_X | LIVE_Y | LIVE_S | LIVE_FLAGS;
    int fail = 0, printed = 0, t;
    int scale = 1;
    { const char* e = getenv("REVS_VALIDATE_CASES"); if (e) scale = atoi(e); }
    if (scale < 1) scale = 1;
    const int colourCases = 2000 * scale, walkCases = 1200 * scale,
              patchCases = 600 * scale, runCases = 400 * scale;

    register_fixture("surface_colour_at");
    register_fixture("column_gap_walk");
    register_fixture("fill_column_gaps");
    register_fixture("fill_edge_column_run");
    setenv("REVS_SMC_CONTINUE", "1", 1);

    if (want("surface_colour_at")) {
        int subFail = 0, arms[SC_ARMS] = {0}, i;
        for (t = 0; t < colourCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            c.A = (uint8_t)xs(); c.X = (uint8_t)xs();
            /* The line: below the horizon in three cases of four, so the five arms under it
               get exercised; the position is what the four boundary compares see. */
            pre[PRE_HORIZON_EXTENT] = (uint8_t)(xs() % 0x50);
            c.Y = (xs() % 4) ? (uint8_t)(xs() % (pre[PRE_HORIZON_EXTENT] + 1u))
                             : (uint8_t)xs();
            /* Pull the boundaries and the position into the same narrow range, or the four
               nested compares are decided by the first one nearly every time. */
            pre[PRE_EDGE_COLUMN] = (uint8_t)(xs() % 0x2A);
            pre[0x0554 + c.Y] = (uint8_t)(xs() % 0x2A);
            pre[0x0600 + c.Y] = (uint8_t)(xs() % 0x2A);
            pre[0x0650 + c.Y] = (uint8_t)(xs() % 0x2A);
            pre[0x05A4 + c.Y] = (uint8_t)(xs() % 0x2A);
            /* Both line_attr limits straddle the line, so each arm's "past its limit" exit
               and its table read both happen. */
            pre[0x002C] = (uint8_t)(c.Y + (xs() % 3) - 1);
            pre[0x0029] = (uint8_t)(c.Y + (xs() % 3) - 1);
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            arms[surface_arm(pre, c.Y)]++;
            subFail += diff_run("surface_colour_at", pre, c, surface_colour_at,
                                surface_colour_at__t6502, liveMask, t, &printed);
        }
        fail += subFail;
        for (i = 0; i < SC_ARMS; i++)
            if (arms[i] == 0) {
                printf("[VACUOUS] surface_colour_at: arm %d never taken\n", i);
                fail++;
            }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(arms sky/e0/attr1/e3/attr0/inside = %d/%d/%d/%d/%d/%d)\n",
               "surface_colour_at", colourCases, subFail, arms[0], arms[1], arms[2],
               arms[3], arms[4], arms[5]);
    }

    if (want("column_gap_walk")) {
        int subFail = 0, walked = 0, skipped = 0, trapped = 0, offPage = 0, zpPtr = 0;
        for (t = 0; t < walkCases; t++) {
            Cpu6502 c = zero_cpu();
            unsigned pick;
            fill_random(pre);
            c.A = (uint8_t)xs(); c.X = (uint8_t)xs(); c.Y = (uint8_t)xs();
            /* A column past $27 has no source block and the walk returns at once, so most
               cases get a real one. */
            pre[PRE_EDGE_COLUMN] = (xs() % 8) ? (uint8_t)(xs() % 0x28) : (uint8_t)xs();
            /* The walk is Y down to mem[$82]: keep it a few dozen lines, not a few hundred. */
            pre[PRE_LINE_CURSOR] = (uint8_t)(0x10 + xs() % 0x40);
            pre[PRE_BLOCK_START] = (uint8_t)(pre[PRE_LINE_CURSOR] - 1 - xs() % 0x20);
            pre[PRE_HORIZON_EXTENT] = (uint8_t)(xs() % 0x50);
            pre[PRE_GAP_FALLBACK] = (xs() & 1) ? 0x55 : (uint8_t)xs();
            /* The branch offset: both real arms, and an illegal one that must trap in BOTH
               models rather than run some third path. */
            /* ⚠⚠ THE ILLEGAL OFFSET MUST LAND OUTSIDE THE REGION, not merely off the two
               arms.  A random offset is a legal branch to some other instruction boundary in
               the same code, and several of those (anything at or above $1DC0, which reloads
               Y from span_line_cursor) make the ORACLE loop forever — the first version of
               this fixture hung the harness.  These four all leave the switch, so both models
               trap. */
            { static const uint8_t offRegion[4] = { 0x40, 0x60, 0x7F, 0x81 };
              pick = xs() % 16;
              pre[PRE_GAP_BRANCH] = pick < 7 ? 0x09
                                  : (pick < 14 ? 0xEF : offRegion[xs() % 4]); }
            if (pre[PRE_GAP_BRANCH] == 0x09) skipped++;
            else if (pre[PRE_GAP_BRANCH] == 0xEF) walked++;
            else trapped++;
            /* The store pointer: the engine's own two, or a random zero-page pair — which is
               what makes "the store can land on its own pointer" a tested case. */
            pick = xs() % 8;
            pre[PRE_GAP_POINTER] = pick < 4 ? 0x70 : (pick < 7 ? 0x72 : (uint8_t)xs());
            if (pre[PRE_GAP_POINTER] != 0x70 && pre[PRE_GAP_POINTER] != 0x72) zpPtr++;
            /* ...and one case in eight aims plot_ptr2 into the hardware window. */
            if (xs() % 8 == 0) { pre[0x0072] = (uint8_t)xs(); pre[0x0073] = 0xFE; offPage++; }
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            { int before = subFail;
              subFail += diff_run("column_gap_walk", pre, c, column_gap_walk,
                                column_gap_walk__t6502, liveMask, t, &printed);
              if (subFail != before && getenv("REVS_DEBUG_WALK"))
                printf("  case %d: col=$%02X cur=$%02X end=$%02X off=$%02X fb=$%02X ptr=$%02X "
                       "p70=$%02X%02X p72=$%02X%02X hz=$%02X\n", t,
                       pre[PRE_EDGE_COLUMN], pre[PRE_LINE_CURSOR], pre[PRE_BLOCK_START],
                       pre[PRE_GAP_BRANCH], pre[PRE_GAP_FALLBACK], pre[PRE_GAP_POINTER],
                       pre[0x0071], pre[0x0070], pre[0x0073], pre[0x0072],
                       pre[PRE_HORIZON_EXTENT]); }
        }
        fail += subFail;
        if (!walked || !skipped || !trapped || !offPage || !zpPtr) {
            printf("[VACUOUS] column_gap_walk: %d table-pass, %d block-pass, %d trap, "
                   "%d into SHEILA, %d random zp pointer — all must be non-zero\n",
                   walked, skipped, trapped, offPage, zpPtr);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(%d table-pass, %d block-pass, %d trap, %d SHEILA, %d random zp)\n",
               "column_gap_walk", walkCases, subFail, walked, skipped, trapped,
               offPage, zpPtr);
    }

    if (want("fill_column_gaps")) {
        int subFail = 0;
        for (t = 0; t < patchCases; t++) {
            Cpu6502 c = zero_cpu();
            fill_random(pre);
            /* The three registers ARE the patch, so they are the input: the two real
               configurations most of the time, a random triple the rest. */
            if (xs() & 1) { c.X = 0x72; c.Y = 0xEF; c.A = 0x00; }
            else if (xs() & 1) { c.X = 0x70; c.Y = 0x09; c.A = 0x55; }
            else { c.X = (uint8_t)xs(); c.Y = (xs() & 1) ? 0x09 : 0xEF; c.A = (uint8_t)xs(); }
            pre[PRE_EDGE_COLUMN] = (xs() % 8) ? (uint8_t)(xs() % 0x28) : (uint8_t)xs();
            pre[PRE_LINE_CURSOR] = (uint8_t)(0x10 + xs() % 0x40);
            pre[PRE_BLOCK_START] = (uint8_t)(pre[PRE_LINE_CURSOR] - 1 - xs() % 0x20);
            pre[PRE_HORIZON_EXTENT] = (uint8_t)(xs() % 0x50);
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            subFail += diff_run("fill_column_gaps", pre, c, fill_column_gaps,
                                fill_column_gaps__t6502, liveMask, t, &printed);
        }
        fail += subFail;
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(the register-to-patch-byte mapping; the walk is column_gap_walk's fixture)\n",
               "fill_column_gaps", patchCases, subFail);
    }

    if (want("fill_edge_column_run")) {
        int subFail = 0, oneColumn = 0, multi = 0;
        for (t = 0; t < runCases; t++) {
            Cpu6502 c = zero_cpu();
            unsigned length;
            fill_random(pre);
            /* X = the first column, A = the column to stop at.  The loop tests EQUALITY, so
               an unreachable stop column runs 128 iterations of two walks each: pick the
               run's LENGTH and derive the stop, keeping the engine's own shape (columns 3-6
               and $1A-$22, i.e. runs of three and eight). */
            length = 1 + xs() % 8;
            c.X = (uint8_t)(xs() % 0x20);
            c.A = (uint8_t)(c.X + length);
            c.Y = (uint8_t)(0x10 + xs() % 0x40);
            if (length == 1) oneColumn++; else multi++;
            pre[PRE_HORIZON_EXTENT] = (uint8_t)(xs() % 0x50);
            /* Both passes' pointers, so the run writes where the engine's would. */
            pre[0x0072] = (xs() & 1) ? 0x04 : 0x00;
            pre[0x0073] = pre[0x0072] == 0x04 ? 0x05 : 0x44;
            c.N = xs() & 1; c.V = xs() & 1; c.Z = xs() & 1; c.C = xs() & 1;
            c.D = 0;
            subFail += diff_run("fill_edge_column_run", pre, c, fill_edge_column_run,
                                fill_edge_column_run__t6502, liveMask, t, &printed);
        }
        fail += subFail;
        if (!oneColumn || !multi) {
            printf("[VACUOUS] fill_edge_column_run: %d single-column, %d multi-column runs\n",
                   oneColumn, multi);
            fail++;
        }
        printf("%-32s %7d cases, %d mismatch (must be 0)  live=AXY+flags  "
               "(%d one-column runs, %d longer)\n",
               "fill_edge_column_run", runCases, subFail, oneColumn, multi);
    }

    unsetenv("REVS_SMC_CONTINUE");
    return fail;
}

/* ==========================================================================
   TWINS #44-#49 — THE ENGINE'S MULTIPLY, AND THE NEGATE BESIDE IT
   --------------------------------------------------------------------------
   $0C00 mul8, $0C02 mul8_noinit, $0DBF mul8_accum, $0DB3 mul16_by_pi, $0E42 neg16_math and
   $0E44 neg16_math_noinit.  These are pure arithmetic on four zero-page cells, so the
   fixtures are cheap and can afford to be EXHAUSTIVE where it counts:

   ⭐ mul8_noinit RUNS ALL 65536 OPERAND PAIRS.  The twin replaces eight unrolled add/shift
      steps with one 16-bit multiply plus a replay of the last add's V, and "0 mismatch over
      every input" is the only evidence that turns that from a plausible identity into a
      proven one.  The zero multiplier (no add runs, so the CALLER's V survives) and the
      $FF x $FF corner are inside the sweep by construction.
   ⚠ DECIMAL MODE IS A SEPARATE PASS, not a percentage of a random one.  D changes the result
      byte of every ADC, so with D set the routine is not a multiply at all and the twin falls
      back to a bit-for-bit replay; that path needs its own cases or the exhaustive sweep above
      (which must run with D clear to mean anything) would hide it entirely.
   ========================================================================== */
void mul8(void);              void mul8__t6502(void);
