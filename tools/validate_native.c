    pre[0x248D] = 0x4C;                                          /* JMP $2403 */
    pre[0x24DE] = 0x20; pre[0x24DF] = 0xF3; pre[0x24E0] = 0x12;  /* JSR $12F3 */
    pre[0x24E9] = 0xC9; pre[0x24EA] = 0x0E;                      /* CMP #$0E  */
